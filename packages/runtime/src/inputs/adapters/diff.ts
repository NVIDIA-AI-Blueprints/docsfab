const HUNK_HEADER = /^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@/u;
/** A `diff` command line or an `Index:` line opens a file section wherever it appears. */
const SECTION_OPENER = /^(?:diff (?:--git |--cc |--combined |-[A-Za-z])|Index: )/u;
const COMBINED_OPENER = /^diff --(?:cc|combined) /u;
/** The mbox separator `git format-patch` writes before each patch of a series. */
const MBOX_FROM = /^From [0-9a-f]{40}(?:[0-9a-f]{24})? /u;
/** The commit line `git log -p` and `git show` write before each commit's message. */
const COMMIT_LINE = /^commit [0-9a-f]{40}(?:[0-9a-f]{24})?(?: |$)/u;
/**
 * Lines Git, GNU diff, and Subversion write in a file section's header. The
 * header is the leading run of these; anything after it that is not a hunk is
 * the file's body text.
 */
const HEADER_LINE =
  /^(?:diff |index |Index: |={3,}$|(?:old |new |deleted file |new file )?mode |(?:dis)?similarity index |(?:rename|copy) (?:from|to) |--- |\+\+\+ |Binary files |GIT binary patch$)/u;
/** The mail signature delimiter `git format-patch` writes after a patch's last file. */
const SIGNATURE = "-- ";
const GIT_BINARY_PATCH = "GIT binary patch";
const BINARY_BLOCK = /^(?:literal|delta) \d+$/u;
const BINARY_FILES = /^Binary files (.+) and (.+) differ$/u;

