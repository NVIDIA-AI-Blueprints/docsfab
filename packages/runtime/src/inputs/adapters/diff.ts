/** One original line, by byte offsets. */
interface Line {
  readonly start: number;
  /** End of the content, before the `\n`. */
  readonly contentEnd: number;
  /** The content as UTF-8 without a trailing `\r`, or `undefined` when it is not UTF-8. */
  readonly text: string | undefined;
  /** The content for structure matching: `text`, or its Latin-1 reading when not UTF-8. */
  readonly shape: string;
}

/** Inclusive line indices. */
interface Unit {
  readonly first: number;
  readonly last: number;
}

interface HunkRanges {
  readonly oldStart: number;
  readonly oldLines: number;
  readonly newStart: number;
  readonly newLines: number;
}

interface DiffHunk extends HunkRanges {
  readonly unit: Unit;
  readonly added: number;
  readonly removed: number;
  readonly utf8: boolean;
}

interface DiffNote {
  readonly unit: Unit;
  readonly utf8: boolean;
}

interface DiffFile {
  /** The header lines, with the body text after them when that text is UTF-8. */
  readonly header: Unit;
  /** Whether the header lines alone are UTF-8. */
  readonly headerUtf8: boolean;
  /** Body lines after the header left out because they are not UTF-8. */
  readonly excludedBodyLines: number;
  readonly hunks: readonly DiffHunk[];
  /** Text after a hunk's counts that opens nothing, in original order. */
  readonly notes: readonly DiffNote[];
  readonly oldPath: string | null;
  readonly newPath: string | null;
  readonly change: SourceDiffChange;
  readonly labels: SourceDiffLabel[];
  readonly payloadLines: number;
}

type DiffItem =
  | { readonly kind: "text"; readonly part: "preamble" | "trailer"; readonly unit: Unit }
  | { readonly kind: "file"; readonly file: DiffFile };

/** What a file section's header lines state; `undefined` is "not stated". */
interface HeaderFacts {
  gitPaths?: { old: string; new: string };
  oldMarker?: string;
  newMarker?: string;
  binaryPaths?: { old: string; new: string };
  indexPath?: string;
  renameFrom?: string;
  renameTo?: string;
  copyFrom?: string;
  copyTo?: string;
  added?: boolean;
  deleted?: boolean;
  binary?: boolean;
}

function splitLines(original: Buffer): Line[] {
  const decoder = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });
  const lines: Line[] = [];
  let start = 0;
  // A leading byte order mark is a line of its own, so it reads as message
  // text and the line after it can still open a file.
  if (original[0] === 0xef && original[1] === 0xbb && original[2] === 0xbf) {
    lines.push({ start: 0, contentEnd: 3, text: "﻿", shape: "﻿" });
    start = 3;
  }
  while (start < original.length) {
    const newline = original.indexOf(0x0a, start);
    const contentEnd = newline === -1 ? original.length : newline;
    const content = original.subarray(start, contentEnd);
    let text: string | undefined;
    try {
      text = decoder.decode(content);
    } catch {
      text = undefined;
    }
    const raw = text ?? content.toString("latin1");
    const shape = raw.endsWith("\r") ? raw.slice(0, -1) : raw;
    lines.push({ start, contentEnd, text: text === undefined ? undefined : shape, shape });
    start = newline === -1 ? original.length : newline + 1;
  }
  return lines;
}

/**
 * The ranges of a `@@` line, or `undefined` when the line is not one or names
 * a number the locator contract cannot carry; such a line stays as text.
 */
function hunkRanges(line: string): HunkRanges | undefined {
  const match = HUNK_HEADER.exec(line);
  if (!match) return undefined;
  const ranges = {
    oldStart: Number(match[1]),
    oldLines: match[2] === undefined ? 1 : Number(match[2]),
    newStart: Number(match[3]),
    newLines: match[4] === undefined ? 1 : Number(match[4]),
  };
  return Object.values(ranges).every((value) => value <= SOURCE_DIFF_LOCATOR_MAX_NUMBER)
    ? ranges
    : undefined;
}

/**
 * Decodes a C-style quoted path as Git writes one. Octal escapes are UTF-8
 * bytes, so the bytes are collected first and decoded once.
 */
function unquote(raw: string): { value: string; rest: string } | undefined {
  if (!raw.startsWith('"')) return undefined;
  const bytes: number[] = [];
  const named: Readonly<Record<string, number>> = {
    a: 7,
    b: 8,
    t: 9,
    n: 10,
    v: 11,
    f: 12,
    r: 13,
    '"': 34,
    "\\": 92,
  };
  let index = 1;
  while (index < raw.length) {
    const character = raw[index]!;
    if (character === '"') {
      let value: string;
      try {
        value = new TextDecoder("utf-8", { fatal: true }).decode(new Uint8Array(bytes));
      } catch {
        // Bytes that are not UTF-8, such as a Latin-1 name, have no faithful
        // text. A NUL keeps the prefix for `a/`/`b/` handling and makes the
        // path one no locator admits, so it is carried as null and labeled.
        value = `${new TextDecoder("utf-8").decode(new Uint8Array(bytes))}\0`;
      }
      return { value, rest: raw.slice(index + 1) };
    }
    if (character === "\\") {
      const next = raw[index + 1] ?? "";
      const octal = /^[0-7]{3}/u.exec(raw.slice(index + 1));
      if (octal) {
        bytes.push(Number.parseInt(octal[0], 8));
        index += 4;
        continue;
      }
      const escaped = named[next];
      if (escaped === undefined) return undefined;
      bytes.push(escaped);
      index += 2;
      continue;
    }
    const codePoint = raw.codePointAt(index)!;
    bytes.push(...new TextEncoder().encode(String.fromCodePoint(codePoint)));
    index += codePoint > 0xffff ? 2 : 1;
  }
  return undefined;
}

/** A `---`/`+++` or `Binary files` path: unquoted, without a trailing timestamp. */
function markerPath(raw: string): string {
  return unquote(raw)?.value ?? raw.split("\t")[0]!;
}

/** The two paths of a `diff --git` line, with their prefixes, when they can be told apart. */
function gitHeaderPaths(rest: string): { old: string; new: string } | undefined {
  const quoted = unquote(rest);
  if (quoted) {
    const after = quoted.rest.trimStart();
    return { old: quoted.value, new: unquote(after)?.value ?? after };
  }
  // `a/X b/X` is ambiguous when X holds " b/", so the symmetric reading wins;
  // `X X` is a `--no-prefix` header.
  for (const [left, right] of [
    ["a/", "b/"],
    ["", ""],
  ] as const) {
    const half = (rest.length - 1 - left.length - right.length) / 2;
    if (!Number.isInteger(half) || half <= 0) continue;
    const candidate = rest.slice(left.length, left.length + half);
    if (rest === `${left}${candidate} ${right}${candidate}`) {
      return { old: `${left}${candidate}`, new: `${right}${candidate}` };
    }
  }
  const split = rest.indexOf(" b/");
  if (rest.startsWith("a/") && split > 0) {
    return { old: rest.slice(0, split), new: rest.slice(split + 1) };
  }
  return undefined;
}

function plainPath(raw: string): string {
  return unquote(raw)?.value ?? raw;
}

function recordHeaderLine(facts: HeaderFacts, line: string): void {
  if (line.startsWith("diff --git ")) {
    facts.gitPaths ??= gitHeaderPaths(line.slice("diff --git ".length));
  } else if (line.startsWith("--- ")) {
    facts.oldMarker ??= markerPath(line.slice(4));
  } else if (line.startsWith("+++ ")) {
    facts.newMarker ??= markerPath(line.slice(4));
  } else if (line.startsWith("rename from ")) {
    facts.renameFrom = plainPath(line.slice("rename from ".length));
  } else if (line.startsWith("rename to ")) {
    facts.renameTo = plainPath(line.slice("rename to ".length));
  } else if (line.startsWith("copy from ")) {
    facts.copyFrom = plainPath(line.slice("copy from ".length));
  } else if (line.startsWith("copy to ")) {
    facts.copyTo = plainPath(line.slice("copy to ".length));
  } else if (line.startsWith("new file mode ")) {
    facts.added = true;
  } else if (line.startsWith("deleted file mode ")) {
    facts.deleted = true;
  } else if (line === GIT_BINARY_PATCH) {
    facts.binary = true;
  } else if (line.startsWith("Index: ")) {
    facts.indexPath = line.slice("Index: ".length);
  } else {
    const binary = BINARY_FILES.exec(line);
    if (binary) {
      facts.binary = true;
      facts.binaryPaths = { old: markerPath(binary[1]!), new: markerPath(binary[2]!) };
    }
  }
}

function firstStated<T>(...values: Array<T | undefined>): T | undefined {
  return values.find((value) => value !== undefined);
}

/**
 * Paths and change kind from a section's header. Git's `a/` and `b/` prefixes
 * are removed only when both sides carry them, so a `--no-prefix` path that
 * starts with `a/` keeps it. A path the locator cannot carry, such as an
 * absolute one, becomes `null` and is labeled.
 */
function describeFile(facts: HeaderFacts): {
  oldPath: string | null;
  newPath: string | null;
  change: SourceDiffChange;
  unrepresentable: boolean;
} {
  const prefixed = (old: string | undefined, next: string | undefined): boolean =>
    old !== undefined &&
    next !== undefined &&
    (old.startsWith("a/") || old === "/dev/null") &&
    (next.startsWith("b/") || next === "/dev/null");
  const markersPrefixed = prefixed(facts.oldMarker, facts.newMarker);
  const binaryPrefixed = prefixed(facts.binaryPaths?.old, facts.binaryPaths?.new);
  const gitPrefixed = prefixed(facts.gitPaths?.old, facts.gitPaths?.new);
  const strip = (path: string | undefined, prefix: string, stripIt: boolean) =>
    path === undefined
      ? undefined
      : path === "/dev/null"
        ? null
        : stripIt && path.startsWith(prefix)
          ? path.slice(prefix.length)
          : path;
  let oldPath = firstStated<string | null>(
    facts.renameFrom,
    facts.copyFrom,
    strip(facts.oldMarker, "a/", markersPrefixed),
    strip(facts.binaryPaths?.old, "a/", binaryPrefixed),
    strip(facts.gitPaths?.old, "a/", gitPrefixed),
    facts.indexPath,
  );
  let newPath = firstStated<string | null>(
    facts.renameTo,
    facts.copyTo,
    strip(facts.newMarker, "b/", markersPrefixed),
    strip(facts.binaryPaths?.new, "b/", binaryPrefixed),
    strip(facts.gitPaths?.new, "b/", gitPrefixed),
    facts.indexPath,
  );
  if (facts.added) oldPath = null;
  if (facts.deleted) newPath = null;
  let change: SourceDiffChange = "modified";
  if (facts.renameFrom !== undefined || facts.renameTo !== undefined) change = "renamed";
  else if (facts.copyFrom !== undefined || facts.copyTo !== undefined) change = "copied";
  else if (facts.added || (oldPath === null && typeof newPath === "string")) change = "added";
  else if (facts.deleted || (newPath === null && typeof oldPath === "string")) change = "deleted";
  let unrepresentable = false;
  const carried = (path: string | null | undefined): string | null => {
    if (path === null || path === undefined) return null;
    const normalized = path.normalize("NFC");
    if (isSourceDiffPathAdmitted(normalized)) return normalized;
    unrepresentable = true;
    return null;
  };
  return { oldPath: carried(oldPath), newPath: carried(newPath), change, unrepresentable };
}

/** Labels by basename and whole directory segment, never by substring. */
function pathLabels(path: string | null, firstHunkText: readonly string[]): SourceDiffLabel[] {
  if (path === null) return [];
  const segments = path.split("/");
  const name = segments.at(-1) ?? "";
  const directories = segments.slice(0, -1);
  const labels: SourceDiffLabel[] = [];
  if (LOCKFILE_NAMES.has(name)) labels.push("lockfile");
  if (directories.some((segment) => VENDORED_DIRECTORIES.has(segment))) labels.push("vendored");
  if (
    GENERATED_NAME.test(name) ||
    directories.some((segment) => GENERATED_DIRECTORIES.has(segment)) ||
    firstHunkText.some((text) => GENERATED_MARKER.test(text))
  ) {
    labels.push("generated");
  }
  return labels;
}

interface ParsedDiff {
  readonly items: readonly DiffItem[];
  readonly files: readonly DiffFile[];
}

/**
 * Splits a unified diff into message text and file sections. A hunk body is
 * read by its `@@` line counts, so a removed line whose text is `- ` or `--`
 * stays in its hunk. A Git binary patch payload ends at the blank line that
 * closes its last `literal` or `delta` block. Lines after a file's header that
 * open nothing are its body, and lines after a hunk's counts that open nothing
 * are a `note`; a signature delimiter, an mbox `From <sha>` line, or a
 * `commit <sha>` line starts a trailer or a new message instead.
 */
function parseUnifiedDiff(lines: readonly Line[]): ParsedDiff {
  const shape = (at: number) => lines[at]!.shape;
  const opensPlainSection = (at: number): boolean =>
    shape(at).startsWith("--- ") && (lines[at + 1]?.shape.startsWith("+++ ") ?? false);
  const opensFile = (at: number): boolean =>
    SECTION_OPENER.test(shape(at)) || opensPlainSection(at);
  const opensMessage = (at: number): boolean =>
    MBOX_FROM.test(shape(at)) || COMMIT_LINE.test(shape(at));
  const allUtf8 = (unit: Unit) =>
    lines.slice(unit.first, unit.last + 1).every((line) => line.text !== undefined);

  const items: DiffItem[] = [];
  const files: DiffFile[] = [];
  let index = 0;
  while (index < lines.length) {
    if (!opensFile(index) || opensMessage(index)) {
      const first = index;
      const part = index === 0 || opensMessage(index) ? "preamble" : "trailer";
      index += 1;
      while (index < lines.length && !opensFile(index) && !opensMessage(index)) index += 1;
      // A run of empty lines has no byte to cite, so it is neither a span nor
      // counted as a message; any other text, whitespace included, is a span.
      const empty = lines.slice(first, index).every((line) => line.contentEnd === line.start);
      if (!empty) items.push({ kind: "text", part, unit: { first, last: index - 1 } });
      continue;
    }

    const facts: HeaderFacts = {};
    const combined = COMBINED_OPENER.test(shape(index));
    const headerFirst = index;
    let sawMarkers = false;
    let binary = false;
    // The header is the leading run of header lines; the rest, such as a
    // combined diff's `@@@` text or `diff -r`'s `Only in` notes, is body.
    let headerLast = headerFirst;
    for (let first = true; index < lines.length; first = false) {
      const line = shape(index);
      if (!first) {
        if (hunkRanges(line) || SECTION_OPENER.test(line) || opensMessage(index)) break;
        if (line === SIGNATURE || (opensPlainSection(index) && sawMarkers)) break;
      }
      if (opensPlainSection(index)) sawMarkers = true;
      if (first || (headerLast === index - 1 && HEADER_LINE.test(line))) {
        headerLast = index;
        const text = lines[index]!.text;
        if (text !== undefined) recordHeaderLine(facts, text);
      }
      index += 1;
      if (line === GIT_BINARY_PATCH && headerLast === index - 1) {
        binary = true;
        break;
      }
    }
    const headerRun = { first: headerFirst, last: headerLast };
    const bodyLines = index - 1 - headerLast;
    // A body that is not UTF-8 is left out, so the header span stops before it.
    const bodyUtf8 = bodyLines === 0 || allUtf8({ first: headerLast + 1, last: index - 1 });
    const header = bodyUtf8 ? { first: headerFirst, last: index - 1 } : headerRun;
    const excludedBodyLines = bodyUtf8 ? 0 : bodyLines;

    // A payload is `literal`/`delta` blocks, each closed by a blank line. Its
    // base85 data lines hold no space, so a line with one ends it even when the
    // closing blank line is missing.
    let payloadLines = 0;
    while (binary && index < lines.length && BINARY_BLOCK.test(shape(index))) {
      index += 1;
      payloadLines += 1;
      while (index < lines.length && shape(index) !== "" && !shape(index).includes(" ")) {
        index += 1;
        payloadLines += 1;
      }
      if (index < lines.length && shape(index) === "") {
        index += 1;
        payloadLines += 1;
      }
    }

    const hunks: DiffHunk[] = [];
    const notes: DiffNote[] = [];
    for (
      let ranges = !binary && index < lines.length ? hunkRanges(shape(index)) : undefined;
      ranges !== undefined;
      ranges = index < lines.length ? hunkRanges(shape(index)) : undefined
    ) {
      const first = index;
      index += 1;
      let oldLeft = ranges.oldLines;
      let newLeft = ranges.newLines;
      let added = 0;
      let removed = 0;
      while (index < lines.length && (oldLeft > 0 || newLeft > 0)) {
        const line = shape(index);
        const marker = line[0];
        if (marker === "+") {
          newLeft -= 1;
          added += 1;
        } else if (marker === "-") {
          oldLeft -= 1;
          removed += 1;
        } else if (marker === " " || line === "") {
          oldLeft -= 1;
          newLeft -= 1;
        } else if (marker !== "\\") {
          break;
        }
        index += 1;
      }
      while (index < lines.length && shape(index).startsWith("\\")) index += 1;
      const unit = { first, last: index - 1 };
      hunks.push({ ...ranges, unit, added, removed, utf8: allUtf8(unit) });
      // Lines after the hunk's counts that open nothing, such as a `diff -r`
      // `Only in` note, are the file's note text, judged apart from the hunk.
      const noteFirst = index;
      while (
        index < lines.length &&
        !hunkRanges(shape(index)) &&
        !opensFile(index) &&
        !opensMessage(index) &&
        shape(index) !== SIGNATURE
      ) {
        index += 1;
      }
      const noteLines = lines.slice(noteFirst, index);
      if (noteLines.some((line) => line.contentEnd > line.start)) {
        const note = { first: noteFirst, last: index - 1 };
        notes.push({ unit: note, utf8: allUtf8(note) });
      }
    }

    const described = describeFile(facts);
    const headerUtf8 = allUtf8(headerRun);
    const firstHunk = hunks[0];
    const headText: string[] = [];
    if (firstHunk !== undefined && firstHunk.utf8) {
      let newLine = firstHunk.newStart;
      for (let at = firstHunk.unit.first + 1; at <= firstHunk.unit.last; at += 1) {
        if (newLine > GENERATED_MARKER_HEAD_LINES) break;
        const text = lines[at]!.text ?? "";
        if (text.startsWith("-") || text.startsWith("\\")) continue;
        headText.push(text);
        newLine += 1;
      }
    }
    const labels = new Set<SourceDiffLabel>(
      pathLabels(described.newPath ?? described.oldPath, headText),
    );
    if (binary || facts.binary) labels.add("binary");
    if (combined) labels.add("combined");
    if (
      !headerUtf8 ||
      !bodyUtf8 ||
      hunks.some((hunk) => !hunk.utf8) ||
      notes.some((note) => !note.utf8)
    ) {
      labels.add("non-utf8");
    }
    if (described.unrepresentable) labels.add("unrepresentable-path");
    const file: DiffFile = {
      header,
      headerUtf8,
      excludedBodyLines,
      notes,
      hunks,
      oldPath: described.oldPath,
      newPath: described.newPath,
      change: described.change,
      labels: [...labels].sort(),
      payloadLines,
    };
    files.push(file);
    items.push({ kind: "file", file });
  }
  return { items, files };
}

function plural(count: number, noun: string, nouns = `${noun}s`): string {
  return `${count} ${count === 1 ? noun : nouns}`;
}

function sum(values: readonly number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

function fileAdded(file: DiffFile): number {
  return sum(file.hunks.map((hunk) => hunk.added));
}

function fileRemoved(file: DiffFile): number {
  return sum(file.hunks.map((hunk) => hunk.removed));
}

/**
 * A file's path or paths for its manifest row. Each path is one quoted token,
 * so path text cannot read as counts, labels, or a rename arrow; an unquoted
 * parenthesized phrase means no path is carried.
 */
function displayPath(file: DiffFile): string {
  const quoted = (path: string) => `"${escapePathText(path)}"`;
  if ((file.change === "renamed" || file.change === "copied") && file.oldPath && file.newPath) {
    return `${quoted(file.oldPath)} -> ${quoted(file.newPath)}`;
  }
  const path = file.newPath ?? file.oldPath;
  if (path !== null) return quoted(path);
  return file.labels.includes("unrepresentable-path") ? "(path not carried)" : "(path not stated)";
}

function manifestRows(parsed: ParsedDiff, excludedTextLines: number): string[] {
  const messages = parsed.items.filter((item) => item.kind === "text" && item.part === "preamble");
  const trailers = parsed.items.filter((item) => item.kind === "text" && item.part === "trailer");
  const summary = [
    `diff manifest: ${plural(parsed.files.length, "file")}`,
    plural(sum(parsed.files.map((file) => file.hunks.length)), "hunk"),
    `+${sum(parsed.files.map(fileAdded))} -${sum(parsed.files.map(fileRemoved))} lines`,
  ].join(", ");
  const notes = [
    ...(messages.length > 0 ? [plural(messages.length, "message")] : []),
    ...(trailers.length > 0 ? [plural(trailers.length, "trailer")] : []),
    ...(excludedTextLines > 0
      ? [`${plural(excludedTextLines, "message line")} not extracted (not UTF-8)`]
      : []),
  ];
  const rows = [[summary, ...notes].join("; ")];
  parsed.files.forEach((file, index) => {
    const skippedHunks = file.hunks.filter((hunk) => !hunk.utf8).length;
    const skippedNoteLines = sum(
      file.notes.filter((note) => !note.utf8).map((note) => note.unit.last - note.unit.first + 1),
    );
    rows.push(
      [
        `file ${index + 1}: ${file.change} ${displayPath(file)}`,
        `+${fileAdded(file)} -${fileRemoved(file)}`,
        plural(file.hunks.length, "hunk"),
        ...(file.labels.length > 0 ? [`labels: ${file.labels.join(", ")}`] : []),
        ...(file.payloadLines > 0
          ? [`${plural(file.payloadLines, "encoded binary line")} not extracted`]
          : []),
        ...(file.excludedBodyLines > 0
          ? [`${plural(file.excludedBodyLines, "body line")} not extracted (not UTF-8)`]
          : []),
        ...(skippedHunks > 0
          ? [`${plural(skippedHunks, "hunk body", "hunk bodies")} not extracted (not UTF-8)`]
          : []),
        ...(skippedNoteLines > 0
          ? [`${plural(skippedNoteLines, "note line")} not extracted (not UTF-8)`]
          : []),
      ].join("; "),
    );
  });
  return rows;
}

/** Whole rows packed into texts of at most `maxBytes`; a longer row is a text of its own. */
function packRows(rows: readonly string[], maxBytes: number): string[] {
  const packed: string[] = [];
  let current: string[] = [];
  let currentBytes = 0;
  for (const row of rows) {
    const bytes = Buffer.byteLength(row, "utf8");
    if (current.length > 0 && currentBytes + 1 + bytes > maxBytes) {
      packed.push(current.join("\n"));
      current = [];
      currentBytes = 0;
    }
    currentBytes += (current.length > 0 ? 1 : 0) + bytes;
    current.push(row);
  }
  if (current.length > 0) packed.push(current.join("\n"));
  return packed;
}

function unscopedLocator(
  part: "manifest" | "preamble" | "trailer",
  range: { startByte: number; endByte: number } | null,
): SourceDiffLocatorV1 {
  return {
    kind: "diff",
    part,
    fileOrdinal: null,
    oldPath: null,
    newPath: null,
    change: null,
    labels: [],
    hunkOrdinal: null,
    hunkCount: null,
    oldStart: null,
    oldLines: null,
    newStart: null,
    newLines: null,
    startByte: range?.startByte ?? null,
    endByte: range?.endByte ?? null,
  };
}

function fileLocator(
  file: DiffFile,
  ordinal: number,
  part: "file" | "header" | "hunk" | "note",
  range: { startByte: number; endByte: number },
): SourceDiffLocatorV1 {
  return {
    kind: "diff",
    part,
    fileOrdinal: ordinal,
    oldPath: file.oldPath,
    newPath: file.newPath,
    change: file.change,
    labels: file.labels,
    hunkOrdinal: null,
    hunkCount: part === "hunk" || part === "note" ? null : file.hunks.length,
    oldStart: null,
    oldLines: null,
    newStart: null,
    newLines: null,
    startByte: range.startByte,
    endByte: range.endByte,
  };
}

function fileLastLine(file: DiffFile): number {
  return Math.max(
    file.header.last,
    file.hunks.at(-1)?.unit.last ?? 0,
    file.notes.at(-1)?.unit.last ?? 0,
  );
}

/**
 * Chooses, per file, between a span per hunk and one span for the whole file.
 * Every file keeps per-hunk spans while the total fits the span ceiling;
 * otherwise the files that save the most spans are read whole first, so a
 * large diff stays bindable without dropping a byte. A file with any text left
 * out is never read whole, since its spans would not be one original slice.
 */
function wholeFileOrdinals(
  files: readonly DiffFile[],
  textOf: (unit: Unit) => string,
  fixedSpans: number,
  maxSpans: number,
  maxSpanBytes: number,
): ReadonlySet<number> {
  const costs = files.map((file, index) => {
    const header = sourceSegmentSpanCount(textOf(file.header), maxSpanBytes);
    if (file.hunks.length === 0) return { index, perHunk: header, saving: 0 };
    // A hunk that is not UTF-8 keeps at most its `@@` line, one span.
    const perHunk =
      (file.headerUtf8 ? header : 0) +
      sum(
        file.hunks.map((hunk) =>
          hunk.utf8 ? sourceSegmentSpanCount(textOf(hunk.unit), maxSpanBytes) : 1,
        ),
      ) +
      sum(
        file.notes.map((note) =>
          note.utf8 ? sourceSegmentSpanCount(textOf(note.unit), maxSpanBytes) : 0,
        ),
      );
    const coalescible =
      file.headerUtf8 &&
      file.excludedBodyLines === 0 &&
      file.hunks.every((hunk) => hunk.utf8) &&
      file.notes.every((note) => note.utf8);
    const whole = coalescible
      ? sourceSegmentSpanCount(
          textOf({ first: file.header.first, last: fileLastLine(file) }),
          maxSpanBytes,
        )
      : perHunk;
    return { index, perHunk, saving: perHunk - whole };
  });
  let total = fixedSpans + sum(costs.map((cost) => cost.perHunk));
  const whole = new Set<number>();
  if (total <= maxSpans) return whole;
  const candidates = costs
    .filter((cost) => cost.saving > 0)
    .sort((left, right) => right.saving - left.saving || left.index - right.index);
  for (const candidate of candidates) {
    if (total <= maxSpans) break;
    whole.add(candidate.index);
    total -= candidate.saving;
  }
  return whole;
}

function extractDiff(request: SourceExtractionRequestV1): SourceExtractionResultV1 {
  const original = Buffer.from(
    request.bytes.buffer,
    request.bytes.byteOffset,
    request.bytes.byteLength,
  );
  const lines = splitLines(original);
  const parsed = parseUnifiedDiff(lines);
  const { maxSpanBytes, maxSpans } = request.limits;
  const rangeOf = (unit: Unit) => ({
    startByte: lines[unit.first]!.start,
    endByte: lines[unit.last]!.contentEnd,
  });
  const textOf = (unit: Unit): string => {
    const range = rangeOf(unit);
    return original.subarray(range.startByte, range.endByte).toString("utf8");
  };
  const utf8 = (unit: Unit) =>
    lines.slice(unit.first, unit.last + 1).every((line) => line.text !== undefined);

  const limitations = new Set<SourceRepresentationLimitation>();
  let excludedTextLines = 0;
  for (const item of parsed.items) {
    if (item.kind === "text" && !utf8(item.unit)) {
      excludedTextLines += item.unit.last - item.unit.first + 1;
    }
  }

  const segments: SourceExtractionSegmentV1[] = [];
  for (const chunk of packRows(manifestRows(parsed, excludedTextLines), maxSpanBytes)) {
    segments.push({ text: chunk, locator: unscopedLocator("manifest", null) });
  }
  const textSegments = new Map<DiffItem, SourceExtractionSegmentV1>();
  for (const item of parsed.items) {
    if (item.kind !== "text") continue;
    if (!utf8(item.unit)) {
      limitations.add("non-text-content-excluded");
      continue;
    }
    textSegments.set(item, {
      text: textOf(item.unit),
      locator: unscopedLocator(item.part, rangeOf(item.unit)),
    });
  }
  const fixedSpans = sum(
    [...segments, ...textSegments.values()].map((segment) =>
      sourceSegmentSpanCount(segment.text, maxSpanBytes),
    ),
  );
  const whole = wholeFileOrdinals(parsed.files, textOf, fixedSpans, maxSpans, maxSpanBytes);

  let fileIndex = 0;
  for (const item of parsed.items) {
    if (item.kind === "text") {
      const segment = textSegments.get(item);
      if (segment) segments.push(segment);
      continue;
    }
    const file = item.file;
    const index = fileIndex;
    fileIndex += 1;
    const ordinal = index + 1;
    if (
      file.payloadLines > 0 ||
      file.excludedBodyLines > 0 ||
      file.notes.some((note) => !note.utf8)
    ) {
      limitations.add("non-text-content-excluded");
    }
    if (!file.headerUtf8) limitations.add("unsupported-encoding");
    if (file.hunks.length === 0 || whole.has(index)) {
      const unit = { first: file.header.first, last: fileLastLine(file) };
      if (file.headerUtf8) {
        segments.push({
          text: textOf(unit),
          locator: fileLocator(file, ordinal, "file", rangeOf(unit)),
        });
      }
      continue;
    }
    if (file.headerUtf8) {
      segments.push({
        text: textOf(file.header),
        locator: fileLocator(file, ordinal, "header", rangeOf(file.header)),
      });
    }
    const fileSegments: Array<{ first: number; segment: SourceExtractionSegmentV1 }> = [];
    file.hunks.forEach((hunk, hunkIndex) => {
      // A hunk that is not UTF-8 keeps only its `@@` line, when that line decodes.
      const unit = hunk.utf8 ? hunk.unit : { first: hunk.unit.first, last: hunk.unit.first };
      if (!hunk.utf8) limitations.add("non-text-content-excluded");
      if (!utf8(unit)) return;
      fileSegments.push({
        first: unit.first,
        segment: {
          text: textOf(unit),
          locator: {
            ...fileLocator(file, ordinal, "hunk", rangeOf(unit)),
            hunkOrdinal: hunkIndex + 1,
            oldStart: hunk.oldStart,
            oldLines: hunk.oldLines,
            newStart: hunk.newStart,
            newLines: hunk.newLines,
          },
        },
      });
    });
    for (const note of file.notes) {
      if (!note.utf8) continue;
      fileSegments.push({
        first: note.unit.first,
        segment: {
          text: textOf(note.unit),
          locator: fileLocator(file, ordinal, "note", rangeOf(note.unit)),
        },
      });
    }
    fileSegments.sort((left, right) => left.first - right.first);
    segments.push(...fileSegments.map((entry) => entry.segment));
  }
  return { segments, limitations: [...limitations].sort() };
}

/**
 * The canonical `text/x-diff` extractor. A producer that holds diff bytes, such
 * as a change-source or merged-merge-request producer, passes it to
 * `extractSourceRepresentation` directly rather than defining its own.
 */
export const diffSourceExtractorAdapter: SourceExtractorAdapterV1 = Object.freeze({
  id: DIFF_SOURCE_EXTRACTOR_ID,
  version: "1",
  locatorKind: "diff",
  mediaTypes: Object.freeze([DIFF_SOURCE_MEDIA_TYPE, PATCH_SOURCE_MEDIA_TYPE]),
  defaultOptions: Object.freeze({
    binaryPatchPayload: "excluded",
    lineTerminators: "verbatim",
    manifest: "files",
    nonUtf8Bodies: "excluded",
    spans: "hunk-or-whole-file",
  }),
  extract: extractDiff,
});
