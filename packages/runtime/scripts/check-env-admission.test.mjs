describe("env-admission mirrors in a tree without the CI owner", () => {
  it("skips the CI mirror by name when its owner is absent", SHIPPED_CLI_CASE, () => {
    const repo = partialRepo();
    try {
      // The tree holds what the export keeps beside an excluded entry, and
      // nothing the export leaves out, whether mirrored, linked or copied.
      for (const kept of ["docs/reference", "packages/runtime/docs/reference", "config/limits"]) {
        assert.equal(existsSync(join(repo.root, kept)), true, kept);
      }
      for (const left of [
        ".gitlab",
        "docs/agents",
        "packages/runtime/docs/internal",
        "config/limits-deploy.json",
      ]) {
        assert.equal(existsSync(join(repo.root, left)), false, left);
      }
      assert.deepEqual(
        readdirSync(join(repo.root, "config/limits-allowlist")).filter((name) =>
          name.startsWith("deploy."),
        ),
        [],
      );
      const result = runCli(repo, ["--check", "--committed-only"]);
      assert.equal(result.status, 0, result.stderr);
      assert.equal(
        result.stdout,
        [
          SHELL_SKIP_LINE,
          "packages/runtime/src/config/env-admission.generated.ts: not checked here, the build generates it (scripts/ensure-derived.mjs)",
          "packages/runtime/scripts/offline-test-env.generated.mjs: not checked here, the build generates it (scripts/ensure-derived.mjs)",
          "Env-admission mirrors are current ()",
          "",
        ].join("\n"),
      );
    } finally {
      repo.remove();
    }
  });

  it("refuses a missing or stale CI mirror when its owner is present", SHIPPED_CLI_CASE, () => {
    const repo = partialRepo();
    try {
      mkdirSync(join(repo.root, ".gitlab/ci"), { recursive: true });
      writeFileSync(join(repo.root, ".gitlab/ci/runtime-run.sh"), "#!/usr/bin/env bash\n");
      const refusal =
        "check:env-admission failed: .gitlab/ci/runtime-run-env.generated.sh drifted from config/env-admission.yaml; run npm run generate:env-admission\n";
      const missing = runCli(repo, ["--check", "--committed-only"]);
      assert.equal(missing.status, 1, missing.stdout);
      assert.equal(missing.stderr, refusal);
      writeFileSync(join(repo.root, ".gitlab/ci/runtime-run-env.generated.sh"), "stale\n");
      const stale = runCli(repo, ["--check", "--committed-only"]);
      assert.equal(stale.status, 1, stale.stdout);
      assert.equal(stale.stderr, refusal);
    } finally {
      repo.remove();
    }
  });

  it("generates only the mirrors whose owner is present", SHIPPED_CLI_CASE, () => {
    const repo = partialRepo(["config", "packages/runtime/scripts", "packages/runtime/src/config"]);
    try {
      const result = runCli(repo, []);
      assert.equal(result.status, 0, result.stderr);
      assert.equal(
        result.stdout,
        `${SHELL_SKIP_LINE}\nUpdated env-admission mirrors: packages/runtime/src/config/env-admission.generated.ts, packages/runtime/scripts/offline-test-env.generated.mjs\n`,
      );
      assert.equal(existsSync(join(repo.root, ".gitlab")), false);
      assert.equal(
        readFileSync(
          join(repo.root, "packages/runtime/src/config/env-admission.generated.ts"),
          "utf8",
        ),
        renderTypeScript(loadEnvAdmission()),
      );
    } finally {
      repo.remove();
    }
  });

  it(
    "--committed-only checks the CI mirror and names the code mirrors it leaves to the build",
    SHIPPED_CLI_CASE,
    () => {
      const repo = partialRepo([
        "config",
        "packages/runtime/scripts",
        "packages/runtime/src/config",
      ]);
      try {
        const shell = join(repo.root, ".gitlab/ci/runtime-run-env.generated.sh");
        mkdirSync(dirname(shell), { recursive: true });
        writeFileSync(join(repo.root, ".gitlab/ci/runtime-run.sh"), "#!/usr/bin/env bash\n");
        writeFileSync(shell, renderShell(loadEnvAdmission()));
        for (const path of [
          "packages/runtime/src/config/env-admission.generated.ts",
          "packages/runtime/scripts/offline-test-env.generated.mjs",
        ]) {
          const output = join(repo.root, path);
          if (existsSync(output)) unlinkSync(output);
        }

        const committed = runCli(repo, ["--check", "--committed-only"]);
        assert.equal(committed.status, 0, committed.stderr);
        assert.equal(
          committed.stdout,
          [
            "packages/runtime/src/config/env-admission.generated.ts: not checked here, the build generates it (scripts/ensure-derived.mjs)",
            "packages/runtime/scripts/offline-test-env.generated.mjs: not checked here, the build generates it (scripts/ensure-derived.mjs)",
            "Env-admission mirrors are current (.gitlab/ci/runtime-run-env.generated.sh)",
            "",
          ].join("\n"),
        );
        // The adjacent case: without the flag the same tree refuses both absent mirrors.
        const full = runCli(repo, ["--check"]);
        assert.equal(full.status, 1, full.stdout);
        assert.equal(
          full.stderr,
          "check:env-admission failed: packages/runtime/src/config/env-admission.generated.ts drifted from config/env-admission.yaml; run npm run generate:env-admission\npackages/runtime/scripts/offline-test-env.generated.mjs drifted from config/env-admission.yaml; run npm run generate:env-admission\n",
        );
        // The committed CI mirror still gates under the flag.
        writeFileSync(shell, "stale\n");
        const stale = runCli(repo, ["--check", "--committed-only"]);
        assert.equal(stale.status, 1, stale.stdout);
        assert.equal(
          stale.stderr,
          "check:env-admission failed: .gitlab/ci/runtime-run-env.generated.sh drifted from config/env-admission.yaml; run npm run generate:env-admission\n",
        );
      } finally {
        repo.remove();
      }
    },
  );

  it(
    "npm run check:env-admission refuses a stale committed CI mirror without rewriting it",
    SHIPPED_CLI_CASE,
    () => {
      const repo = partialRepo([
        "config",
        "packages/runtime/scripts",
        "packages/runtime/src/config",
      ]);
      try {
        const shell = join(repo.root, ".gitlab/ci/runtime-run-env.generated.sh");
        mkdirSync(dirname(shell), { recursive: true });
        writeFileSync(join(repo.root, ".gitlab/ci/runtime-run.sh"), "#!/usr/bin/env bash\n");
        writeFileSync(shell, "stale\n");
        const result = spawnSync("npm", ["run", "--silent", "check:env-admission"], {
          cwd: join(repo.root, "packages/runtime"),
          encoding: "utf8",
        });
        assert.equal(result.status, 1, result.stdout);
        assert.match(
          result.stderr,
          /^check:env-admission failed: \.gitlab\/ci\/runtime-run-env\.generated\.sh drifted from config\/env-admission\.yaml; run npm run generate:env-admission$/mu,
        );
        assert.equal(readFileSync(shell, "utf8"), "stale\n");
      } finally {
        repo.remove();
      }
    },
  );

  it("refuses an unknown argument and --committed-only without --check", SHIPPED_CLI_CASE, () => {
    const repo = partialRepo();
    try {
      const cases = [
        [["--committed-only"], "--committed-only narrows --check and does not apply to generation"],
        [["--chek"], "Unknown argument: --chek"],
      ];
      for (const [args, message] of cases) {
        const result = runCli(repo, args);
        assert.equal(result.status, 1, result.stdout);
        assert.equal(result.stderr, `check:env-admission failed: ${message}\n`);
        assert.equal(result.stdout, "");
      }
    } finally {
      repo.remove();
    }
  });

  it("runs as a CLI when invoked through a symlink", SHIPPED_CLI_CASE, () => {
    const dir = mkdtempSync(join(tmpdir(), "docsfab-env-admission-symlink-"));
    try {
      const link = join(dir, "check-env-admission-link.mjs");
      symlinkSync(script, link);
      const committedArgs = ["--check", "--committed-only"];
      const direct = spawnSync(process.execPath, [script, ...committedArgs], { encoding: "utf8" });
      const linked = spawnSync(process.execPath, [link, ...committedArgs], { encoding: "utf8" });
      assert.equal(direct.status, 0, direct.stderr);
      assert.match(direct.stdout, /Env-admission mirrors are current/u);
      assert.equal(linked.status, 0, linked.stderr);
      assert.equal(linked.stdout, direct.stdout);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

/**
 * A repository root for the shipped CLI with the export's omitted paths
 * absent and `copied` paths as real copies; every other entry is a symlink to
 * this checkout. `remove()` unlinks the symlinks before deleting the root.
 */
function partialRepo(copied = ["config", "packages/runtime/scripts"]) {
  const root = mkdtempSync(join(tmpdir(), "docsfab-env-admission-partial-"));
  const links = [];
  const copies = new Set(copied);
  const holdsSelection = (relative) =>
    holdsExportExcluded(relative) || [...copies].some((path) => path.startsWith(`${relative}/`));
  const mirror = (relative) => {
    mkdirSync(join(root, relative), { recursive: true });
    for (const name of readdirSync(join(repositoryRoot, relative))) {
      const child = relative === "" ? name : `${relative}/${name}`;
      if (child === ".git" || isExportExcluded(child)) continue;
      if (copies.has(child)) {
        cpSync(join(repositoryRoot, child), join(root, child), {
          recursive: true,
          filter: (source) => !isExportExcluded(relativePath(repositoryRoot, source)),
        });
      } else if (holdsSelection(child)) {
        mirror(child);
      } else {
        symlinkSync(join(repositoryRoot, child), join(root, child));
        links.push(join(root, child));
      }
    }
  };
  mirror("");
  return {
    root,
    remove() {
      for (const link of links) unlinkSync(link);
      rmSync(root, { recursive: true, force: true });
    },
  };
}

function runCli(repo, args) {
  return spawnSync(
    process.execPath,
    [join(repo.root, "packages/runtime/scripts/check-env-admission.mjs"), ...args],
    { encoding: "utf8" },
  );
}

function admitProjection(declaration) {
  return declaration.purposes.map((purpose) => ({
    id: purpose.id,
    admits: purpose.admits.map((admit) => ({
      name: admit.name,
      kind: admit.kind,
      value: admit.value,
      when: admit.when,
    })),
  }));
}

function withYamlHidden(callback) {
  const Module = process.getBuiltinModule("module");
  const origResolve = Module._resolveFilename;
  Module._resolveFilename = function hideYaml(request, ...rest) {
    if (request === "yaml") {
      const error = new Error("Cannot find module 'yaml'");
      error.code = "MODULE_NOT_FOUND";
      throw error;
    }
    return origResolve.call(this, request, ...rest);
  };
  try {
    return callback();
  } finally {
    Module._resolveFilename = origResolve;
  }
}
