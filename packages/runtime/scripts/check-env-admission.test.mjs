describe("untracked generated code mirrors", () => {
  const checkIgnored = (paths) =>
    spawnSync("git", ["-C", repositoryRoot, "check-ignore", "--no-index", ...paths], {
      encoding: "utf8",
    });
  const trackedPaths = (paths) =>
    spawnSync("git", ["-C", repositoryRoot, "ls-files", "--", ...paths], {
      encoding: "utf8",
    });

  it("ignores exactly the model-output code mirrors and keeps the rule reference tracked", () => {
    const ignored = checkIgnored([...MODEL_OUTPUT_BUILD_MIRRORS, MODEL_OUTPUT_REFERENCE]);
    assert.equal(
      ignored.status,
      0,
      `git check-ignore should find each model-output code mirror: ${ignored.stderr}`,
    );
    assert.deepEqual(
      ignored.stdout.split("\n").filter(Boolean).sort(),
      [...MODEL_OUTPUT_BUILD_MIRRORS].sort(),
    );
    const tracked = trackedPaths([...MODEL_OUTPUT_BUILD_MIRRORS, MODEL_OUTPUT_REFERENCE]);
    assert.equal(tracked.status, 0, `git ls-files failed: ${tracked.stderr}`);
    assert.deepEqual(tracked.stdout.split("\n").filter(Boolean).sort(), [MODEL_OUTPUT_REFERENCE]);
  });

  it("ignores and leaves untracked exactly the env-admission code mirrors", () => {
    const ignored = checkIgnored(ENV_ADMISSION_BUILD_MIRRORS);
    assert.equal(
      ignored.status,
      0,
      `git check-ignore should find each env-admission code mirror: ${ignored.stderr}`,
    );
    assert.deepEqual(
      ignored.stdout.split("\n").filter(Boolean).sort(),
      [...ENV_ADMISSION_BUILD_MIRRORS].sort(),
    );
    const tracked = trackedPaths(ENV_ADMISSION_BUILD_MIRRORS);
    assert.equal(tracked.status, 0, `git ls-files failed: ${tracked.stderr}`);
    assert.deepEqual(tracked.stdout.split("\n").filter(Boolean).sort(), []);
  });

  it(
    "keeps the CI shell mirror tracked and outside the build-mirror ignore set",
    internalOnly(CI_ENV_ADMISSION_SHELL, "the CI shell mirror is not part of the public export"),
    () => {
      const ignored = checkIgnored([CI_ENV_ADMISSION_SHELL]);
      assert.notEqual(ignored.status, 0, "the committed CI shell mirror must not be ignored");
      const tracked = trackedPaths([CI_ENV_ADMISSION_SHELL]);
      assert.equal(tracked.status, 0, `git ls-files failed: ${tracked.stderr}`);
      assert.deepEqual(tracked.stdout.split("\n").filter(Boolean), [CI_ENV_ADMISSION_SHELL]);
    },
  );
});

