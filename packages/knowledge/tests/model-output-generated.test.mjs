import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

import {
  OUTPUT_GRAMMARS,
  OUTPUT_REPLAY_MODES,
  OUTPUT_RULE_FAMILIES,
  OUTPUT_RULES,
} from "../src/model-output.generated.mjs";

// The knowledge binding of the model-output rule catalog. The runtime
// generator (`packages/runtime/scripts/check-model-output.mjs`) writes it and
// fails CI when it drifts; these checks keep it a self-contained, frozen,
// plain-JavaScript table the knowledge package can load.

test("the generated model-output binding imports nothing", async () => {
  const source = await readFile(new URL("../src/model-output.generated.mjs", import.meta.url), "utf8");
  assert.doesNotMatch(source, /^\s*import\s/mu);
  assert.match(source, /Generated by packages\/runtime\/scripts\/check-model-output\.mjs/u);
});

test("the generated model-output tables are deeply frozen", () => {
  for (const table of [OUTPUT_RULES, OUTPUT_RULE_FAMILIES, OUTPUT_GRAMMARS, OUTPUT_REPLAY_MODES]) {
    assert.equal(Object.isFrozen(table), true);
  }
  const rule = OUTPUT_RULES["revision-accounting-invalid-json"];
  assert.equal(Object.isFrozen(rule), true);
  assert.equal(Object.isFrozen(rule.locations), true);
  assert.throws(() => {
    rule.retry = "terminal";
  }, TypeError);
});

test("every generated rule carries its statement, retry, and family", () => {
  for (const [code, rule] of Object.entries(OUTPUT_RULES)) {
    assert.equal(rule.code, code);
    assert.ok(rule.statement.length > 0, code);
    assert.ok(["model-correctable", "terminal"].includes(rule.retry), code);
    assert.ok(OUTPUT_RULE_FAMILIES[rule.family].codes.includes(code), code);
    if (["authority", "disclosure", "integrity", "host"].includes(rule.kind)) {
      assert.equal(rule.retry, "terminal", code);
    }
  }
});
