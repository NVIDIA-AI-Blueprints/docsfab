import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { cp, link, mkdtemp, readFile, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import {
  CATALOG_SKILL_IDS,
  CatalogSkillCrateError,
  parseCatalogSkillCrateLock,
  readCatalogSkillCrateLock,
  verifyCatalogSkill,
} from "../src/skills/catalog-crate.js";
import { CatalogSkillCrateResolver } from "../src/skills/catalog-crate-resolver.js";
import {
  catalogSkillDirectoriesForWorkflow,
  catalogSkillDirectoryForStep,
  catalogSkillToolsForStep,
} from "../src/skills/catalog-crate-selection.js";
import { createConfinedToolSet } from "../src/harness/confined-tools.js";
import { getWorkflow, listWorkflows } from "../src/workflow-registry/catalog.js";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(projectRoot, "../..");
const skillCrateDirectory = resolve(projectRoot, "skill-crate");
const readTools = ["read", "grep", "find", "ls"] as const;

function sha256(content: Uint8Array | string): string {
  return createHash("sha256").update(content).digest("hex");
}

async function copiedCrate(): Promise<string> {
  const root = await mkdtemp(resolve(tmpdir(), "docsfab-catalog-skill-crate-"));
  const destination = resolve(root, "skill-crate");
  await cp(skillCrateDirectory, destination, { recursive: true });
  return destination;
}

async function mutateLock(
  directory: string,
  mutate: (lock: Record<string, unknown>) => void,
): Promise<void> {
  const path = resolve(directory, "lock.json");
  const lock = JSON.parse(await readFile(path, "utf8")) as Record<string, unknown>;
  mutate(lock);
  await writeFile(path, `${JSON.stringify(lock, null, 2)}\n`);
}

describe("catalog skill crate", () => {
  it("locks the exact public catalog in stable order", async () => {
    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    expect(lock.skills.map((skill) => skill.id)).toEqual(CATALOG_SKILL_IDS);
    // Cardinality plus identity: the landed length assertion moves with the
    // catalog (fourteen public skills, including the semantic knowledge
    // procedure, the Foundation inspection skill, the IA design
    // skill the hosted IA jobs select, and the site scaffold guidance the
    // hosted site-bootstrap job selects),
    // and the named ids keep a rename or a silent substitution from satisfying
    // the count.
    // The installed quality pack refuses an unsorted or duplicated crate the
    // moment a real worker starts -- `skillCrate.skillIds must be sorted and
    // unique` -- and every generator here will emit either without complaint,
    // so the order is asserted against the catalog rather than discovered by a
    // child process. A registration inserted at the wrong point fails here.
    expect([...CATALOG_SKILL_IDS]).toEqual([...CATALOG_SKILL_IDS].sort());
    expect(new Set(CATALOG_SKILL_IDS).size).toBe(CATALOG_SKILL_IDS.length);
    expect(CATALOG_SKILL_IDS).toHaveLength(14);
    expect(CATALOG_SKILL_IDS).toContain("assess-documentation-readiness");
    expect(CATALOG_SKILL_IDS).toContain("doc-context-analyzer");
    expect(CATALOG_SKILL_IDS).toContain("reconcile-product-behavior");
    expect(CATALOG_SKILL_IDS).toContain("repo-bootstrap");
    expect(CATALOG_SKILL_IDS).toContain("template-scaffold-site");
    expect(CATALOG_SKILL_IDS).toContain("tpl-design-ia");
    expect(CATALOG_SKILL_IDS).not.toContain("derive-source-obligations");
    expect(lock.contractHashFormat).toBe("sha256-catalog-skill-contract-v1");
    expect(JSON.stringify(lock)).not.toContain("optional");
    expect(JSON.stringify(lock)).not.toContain("role");
    expect(JSON.stringify(lock)).not.toContain("compatibility");
  });

  it("packages exact generated bytes from the canonical skills owner", async () => {
    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    for (const skill of lock.skills) {
      const canonicalRoot =
        skill.id === "reconcile-product-behavior" ? "packages/knowledge/skills" : "packages/skills";
      expect(skill.sourcePath).toBe(`${canonicalRoot}/${skill.id}/SKILL.md`);
      const [canonical, packaged] = await Promise.all([
        readFile(resolve(repositoryRoot, skill.sourcePath)),
        readFile(resolve(skillCrateDirectory, skill.skillRoot, "SKILL.md")),
      ]);
      expect(packaged).toEqual(canonical);
      expect(sha256(packaged)).toBe(skill.contentSha256);
    }
  });

  it("locks the evaluator report template and binding validator", async () => {
    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    const evaluator = lock.skills.find((skill) => skill.id === "evaluate-document-quality");
    expect(evaluator).toBeDefined();
    expect(evaluator!.files.map((file) => file.path)).toContain(
      "assets/quality-report-template.md",
    );
    expect(evaluator!.files.map((file) => file.path)).toContain(
      "scripts/validate_quality_report.py",
    );
  });

  it("resolves every workflow-selected id directly from the crate", async () => {
    const resolver = new CatalogSkillCrateResolver(skillCrateDirectory);
    for (const workflow of listWorkflows()) {
      const directories = await catalogSkillDirectoriesForWorkflow(skillCrateDirectory, workflow);
      expect(directories).toHaveLength(workflow.steps.length);
      for (const [index, step] of workflow.steps.entries()) {
        const evidence = await resolver.resolveSkill({
          repositoryPath: repositoryRoot,
          workflow,
          step,
        });
        expect(evidence.id).toBe(step.skill);
        expect(directories[index]).toBe(resolve(skillCrateDirectory, step.skill));
      }
    }
  });

  it("fails closed for unknown ids instead of scanning packages/skills", async () => {
    const workflow = listWorkflows()[0];
    expect(workflow).toBeDefined();
    if (!workflow) throw new Error("expected workflow fixture");
    const step = workflow.steps[0];
    expect(step).toBeDefined();
    if (!step) throw new Error("expected workflow step fixture");
    await expect(
      catalogSkillDirectoryForStep({
        skillCrateDirectory,
        step: { ...step, skill: "unknown-catalog-skill" },
      }),
    ).rejects.toMatchObject({ code: "invalid-lock" });
  });

  it("rejects stale requested identities and wider tool grants", async () => {
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory,
        skillId: "audit-documentation",
        grantedTools: readTools,
        expectedVersion: "stale",
      }),
    ).rejects.toMatchObject({ code: "stale" });
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory,
        skillId: "audit-documentation",
        grantedTools: [...readTools, "write"],
      }),
    ).rejects.toMatchObject({ code: "privilege-expanding" });
  });

  it("declares only names the confined tool set actually registers", async () => {
    const workspace = await mkdtemp(resolve(tmpdir(), "docsfab-catalog-skill-tools-"));
    const [readOnly, writable] = await Promise.all([
      createConfinedToolSet({ workspacePath: workspace, allowWrite: false }),
      createConfinedToolSet({ workspacePath: workspace, allowWrite: true }),
    ]);
    const registered = new Set(
      [...readOnly.definitions, ...writable.definitions].map((tool) => tool.name),
    );
    expect(registered.has("Read")).toBe(false);
    expect(registered.has("Glob")).toBe(false);

    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    expect(lock.skills).not.toHaveLength(0);
    for (const skill of lock.skills) {
      expect(skill.toolPolicy.declared).not.toHaveLength(0);
      for (const tool of skill.toolPolicy.declared) {
        expect(
          registered.has(tool),
          `${skill.id} declares "${tool}", which no registered tool provides`,
        ).toBe(true);
        expect(skill.toolPolicy.granted).toContain(tool);
      }
    }
  });

  it("resolves every review-documentation declaration against its own grant", async () => {
    const workflow = getWorkflow("review-documentation");
    expect(workflow.steps).not.toHaveLength(0);
    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    for (const step of workflow.steps) {
      const verified = await verifyCatalogSkill({
        skillCrateDirectory,
        skillId: step.skill,
        grantedTools: catalogSkillToolsForStep(step),
      });
      const declared = verified.skill.toolPolicy.declared;
      expect(declared).not.toHaveLength(0);
      expect(declared.filter((tool) => !catalogSkillToolsForStep(step).includes(tool))).toEqual([]);
      expect(lock.skills.find((skill) => skill.id === step.skill)?.toolPolicy.declared).toEqual(
        declared,
      );
    }
    // Declared names must be granted names: declared ["Read","Grep","Glob"]
    // beside granted ["read","grep","find","ls"] resolves no declared name.
    expect(JSON.stringify(lock.skills.map((skill) => skill.toolPolicy))).not.toMatch(
      /"(Read|Grep|Glob|Edit|Write|Bash)"/u,
    );
  });

  it("fails closed when a declared tool name does not resolve to a registered tool", async () => {
    const crate = await copiedCrate();
    const declare = async (declared: string[]): Promise<void> => {
      await mutateLock(crate, (lock) => {
        const skills = lock.skills as { id: string; toolPolicy: { declared: string[] } }[];
        const target = skills.find((skill) => skill.id === "review-documentation");
        if (!target) throw new Error("expected review-documentation in the crate lock");
        target.toolPolicy.declared = declared;
      });
    };
    const verify = async (): Promise<unknown> =>
      verifyCatalogSkill({
        skillCrateDirectory: crate,
        skillId: "review-documentation",
        grantedTools: readTools,
      }).catch((error: unknown) => error);

    await declare(["Read", "Grep", "Glob"]);
    const claudeNames = await verify();
    expect(claudeNames).toBeInstanceOf(CatalogSkillCrateError);
    expect((claudeNames as CatalogSkillCrateError).code).toBe("unresolved-declared-tool");
    expect((claudeNames as Error).message).toContain('"Glob"');
    await expect(
      new CatalogSkillCrateResolver(crate).resolveSkill({
        step: { skill: "review-documentation", mode: "read-only", kind: "inference" },
      } as never),
    ).rejects.toMatchObject({ code: "unresolved-declared-tool" });

    // Case is load-bearing: dispatch is exact, so "Find" is not "find".
    await declare(["read", "grep", "Find"]);
    const wrongCase = await verify();
    expect((wrongCase as CatalogSkillCrateError).code).toBe("unresolved-declared-tool");
    expect((wrongCase as Error).message).toContain('"Find"');
    expect((wrongCase as Error).message).not.toContain('"read"');

    // Positive control: the same mutation path with canonical names verifies.
    await declare(["read", "grep", "find"]);
    expect(await verify()).toMatchObject({ skill: { id: "review-documentation" } });
  });

  it("rejects duplicate and incomplete lock identities", async () => {
    const duplicate = await copiedCrate();
    await mutateLock(duplicate, (lock) => {
      const skills = lock.skills as unknown[];
      skills.push(skills[0]);
    });
    await expect(readCatalogSkillCrateLock(duplicate)).rejects.toMatchObject({
      code: "duplicate",
    });

    const incomplete = await copiedCrate();
    await mutateLock(incomplete, (lock) => {
      (lock.skills as unknown[]).pop();
    });
    await expect(readCatalogSkillCrateLock(incomplete)).rejects.toMatchObject({
      code: "invalid-lock",
    });
  });

  it("rejects changed, added, and hard-linked files", async () => {
    const changed = await copiedCrate();
    await writeFile(resolve(changed, "audit-documentation", "SKILL.md"), "changed\n");
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory: changed,
        skillId: "audit-documentation",
        grantedTools: readTools,
      }),
    ).rejects.toMatchObject({ code: "checksum-mismatch" });

    const added = await copiedCrate();
    await writeFile(resolve(added, "audit-documentation", "unlocked.txt"), "not locked\n");
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory: added,
        skillId: "audit-documentation",
        grantedTools: readTools,
      }),
    ).rejects.toMatchObject({ code: "file-set-mismatch" });

    const hardLinked = await copiedCrate();
    const skillPath = resolve(hardLinked, "audit-documentation", "SKILL.md");
    const original = await readFile(skillPath);
    await writeFile(resolve(hardLinked, "hard-link-source"), original);
    await writeFile(skillPath, original);
    await link(
      resolve(hardLinked, "hard-link-source"),
      resolve(hardLinked, "audit-documentation", "linked"),
    );
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory: hardLinked,
        skillId: "audit-documentation",
        grantedTools: readTools,
      }),
    ).rejects.toMatchObject({ code: "unsafe-path" });
  });

  it("rejects symbolic links before reading skill bytes", async () => {
    const linked = await copiedCrate();
    const target = resolve(linked, "audit-documentation", "SKILL.md");
    const linkPath = resolve(linked, "audit-documentation", "linked-skill");
    await symlink(target, linkPath);
    await expect(
      verifyCatalogSkill({
        skillCrateDirectory: linked,
        skillId: "audit-documentation",
        grantedTools: readTools,
      }),
    ).rejects.toMatchObject({ code: "unsafe-path" });
  });

  it("rejects unexpected schema fields and credential-bearing values", () => {
    const valid = JSON.parse(
      readFileSync(resolve(skillCrateDirectory, "lock.json"), "utf8"),
    ) as Record<string, unknown>;
    expect(() => parseCatalogSkillCrateLock({ ...valid, optional: true })).toThrow(
      CatalogSkillCrateError,
    );
    expect(() =>
      parseCatalogSkillCrateLock({
        ...valid,
        sourceToken: "glpat-0123456789abcdefghijkl",
      }),
    ).toThrow(CatalogSkillCrateError);
  });

  it("locks invocation metadata as an ordinary hashed sidecar for contract skills", async () => {
    const lock = await readCatalogSkillCrateLock(skillCrateDirectory);
    const contractSkills = [
      "assess-documentation-readiness",
      "audit-documentation",
      "doc-context-analyzer",
      "evaluate-document-quality",
      "lint-documentation",
      "plan-documentation",
      "repo-bootstrap",
      "review-documentation",
      "template-scaffold-site",
      "test-audience-understanding",
      "tpl-design-ia",
      "verify-technical-accuracy",
      "write-documentation",
    ];
    for (const skill of lock.skills) {
      const hasMetadata = skill.files.some((file) => file.path === "invocation.json");
      if (contractSkills.includes(skill.id)) {
        expect(hasMetadata).toBe(true);
      } else {
        expect(hasMetadata).toBe(false);
      }
    }
    const resolver = new CatalogSkillCrateResolver(skillCrateDirectory);
    const metadata = await resolver.resolveInvocationMetadata({
      step: { skill: "write-documentation", mode: "write", kind: "inference" },
    } as never);
    expect(metadata.skillId).toBe("write-documentation");
    expect(metadata.profiles.some((profile) => profile.id === "plain-guidance")).toBe(true);
  });
});
