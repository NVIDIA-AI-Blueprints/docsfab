import { describe, expect, it } from "vitest";

import { parseIaLifecycleArguments } from "../src/ia/lifecycle-cli.js";

const REVISION = "a".repeat(40);

describe("IA lifecycle CLI", () => {
  it("parses the clean analysis, planning, inspection, and approval journey", () => {
    expect(
      parseIaLifecycleArguments([
        "input",
        "create",
        "analysis",
        "--repo",
        "repository",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--json",
      ]),
    ).toMatchObject({
      command: "input",
      operation: "provision",
      packageKind: "analysis-input",
      revision: REVISION,
      task: { kind: "ia-plan", scope: "site", mode: "create" },
      json: true,
    });
    expect(
      parseIaLifecycleArguments([
        "input",
        "provision",
        "planning",
        "--repo",
        "repository",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--analysis-run",
        "analysis-1",
      ]),
    ).toMatchObject({
      command: "input",
      operation: "provision",
      packageKind: "planning-input",
      analysisRunId: "analysis-1",
    });
    expect(
      parseIaLifecycleArguments([
        "input",
        "validate",
        "planning",
        "--repo",
        "repository",
        "--revision",
        REVISION,
        "--scope",
        "page",
        "--target",
        "docs/guide.md",
        "--input-digest",
        "f".repeat(64),
      ]),
    ).toMatchObject({
      command: "input",
      operation: "validate",
      packageKind: "planning-input",
      task: { scope: "page", mode: "reevaluate", target: { sourcePath: "docs/guide.md" } },
      inputDigest: "f".repeat(64),
    });
    expect(
      parseIaLifecycleArguments([
        "approve",
        "--repo",
        "repository",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--run-id",
        "plan-1",
        "--reviewer-policy",
        "private/reviewers.json",
        "--reviewer-id",
        "maintainer:docs",
        "--private-key",
        "private/reviewer.pem",
      ]),
    ).toMatchObject({ command: "approve", planningRunId: "plan-1", reviewerId: "maintainer:docs" });
  });

  it("parses the fixed site-bootstrap cycle request", () => {
    expect(
      parseIaLifecycleArguments(
        [
          "cycle",
          "--repo",
          "repository",
          "--revision",
          REVISION,
          "--expires-at",
          "2099-08-10T12:00:00.000Z",
          "--reviewer-policy",
          "private/reviewers.json",
          "--reviewer-id",
          "maintainer:docs",
          "--private-key",
          "private/reviewer.pem",
          "--json",
        ],
        "/operator",
      ),
    ).toEqual({
      command: "cycle",
      repositoryPath: "/operator/repository",
      revision: REVISION,
      task: { kind: "ia-plan", scope: "site", mode: "create" },
      expiresAt: "2099-08-10T12:00:00.000Z",
      reviewerPolicyPath: "/operator/private/reviewers.json",
      reviewerId: "maintainer:docs",
      privateKeyPath: "/operator/private/reviewer.pem",
      json: true,
    });
  });

  it.each([
    [
      "symbolic revision",
      [
        "input",
        "inspect",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        "HEAD",
        "--scope",
        "site",
        "--mode",
        "create",
      ],
    ],
    [
      "missing expiry",
      [
        "input",
        "provision",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
      ],
    ],
    [
      "manual planning expiry",
      [
        "input",
        "provision",
        "planning",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--analysis-run",
        "run-1",
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
      ],
    ],
    [
      "write authority",
      [
        "input",
        "inspect",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--allow-write",
      ],
    ],
    [
      "path traversal",
      [
        "input",
        "inspect",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "page",
        "--target",
        "../secret.md",
      ],
    ],
    [
      "unknown option",
      [
        "approve",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--run-id",
        "run",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
        "--output",
        "elsewhere",
      ],
    ],
    [
      "provision digest",
      [
        "input",
        "provision",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--input-digest",
        "f".repeat(64),
      ],
    ],
    [
      "invalid digest",
      [
        "input",
        "inspect",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "site",
        "--mode",
        "create",
        "--input-digest",
        "BAD",
      ],
    ],
    [
      "nul target",
      [
        "input",
        "inspect",
        "analysis",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--scope",
        "page",
        "--target",
        "docs/bad\0name.md",
      ],
    ],
    [
      "cycle symbolic revision",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        "HEAD",
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
      ],
    ],
    [
      "cycle missing expiry",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
      ],
    ],
    [
      "cycle noncanonical expiry",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
      ],
    ],
    [
      "cycle unsafe reviewer",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "bad/id",
        "--private-key",
        "k",
      ],
    ],
    [
      "cycle write authority",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
        "--allow-write",
      ],
    ],
    [
      "cycle plan input",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
        "--plan",
        "plan.json",
      ],
    ],
    [
      "cycle task override",
      [
        "cycle",
        "--repo",
        "repo",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
        "--scope",
        "page",
      ],
    ],
    [
      "cycle duplicate",
      [
        "cycle",
        "--repo",
        "repo",
        "--repo",
        "other",
        "--revision",
        REVISION,
        "--expires-at",
        "2099-08-10T12:00:00.000Z",
        "--reviewer-policy",
        "p",
        "--reviewer-id",
        "id",
        "--private-key",
        "k",
      ],
    ],
  ])("rejects %s", (_name, args) => {
    expect(() => parseIaLifecycleArguments(args)).toThrow();
  });
});
