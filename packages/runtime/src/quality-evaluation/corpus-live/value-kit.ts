export function object(value: unknown, code: string): Record<string, unknown> {
  if (!value || typeof value !== "object" || Array.isArray(value)) fail(code);
  return value as Record<string, unknown>;
}

export function exact(value: Record<string, unknown>, allowed: string[], required = allowed): void {
  if (
    Object.keys(value).some((key) => !allowed.includes(key)) ||
    required.some((key) => !Object.hasOwn(value, key))
  )
    fail("live-contract-drift");
}

export function fail(code: string): never {
  throw new Error(`Living-documentation raw evidence rejected (${code}).`);
}
