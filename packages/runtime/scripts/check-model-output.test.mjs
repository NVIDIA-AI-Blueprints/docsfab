  it("refuses a $ref cycle in a canonical schema and walks a deep acyclic one without a depth bound", () => {
    const withSchema = (mutate) => {
      const catalogSources = sources();
      const readCanonical = catalogSources.readCanonical;
      catalogSources.readCanonical = (path) => {
        const schema = structuredClone(readCanonical(path));
        if (path.endsWith("documentation-quality-evaluation.schema.json")) mutate(schema);
        return schema;
      };
      return catalogSources;
    };
    // A finding's evidence item refers back to the finding: a cycle.
    assert.throws(
      () =>
        validateCatalog(
          withSchema((schema) => {
            schema.$defs.evidence.properties.cause = { $ref: "#/$defs/finding" };
          }),
        ),
      /canonical schema \$ref cycle/u,
    );
    // A cycle the member tree never walks, through a conditional subschema,
    // is refused when the record shape inlines it.
    assert.throws(
      () =>
        validateCatalog(
          withSchema((schema) => {
            schema.$defs.evidence.allOf = [{ if: { $ref: "#/$defs/finding" } }];
          }),
        ),
      /canonical schema \$ref cycle; a record shape must be finite/u,
    );
    // Sixty nested objects under a model-judged member, with a shared $ref
    // used twice, are no cycle: the walk and the record shape both finish.
    const deep = withSchema((schema) => {
      let node = { type: "object", properties: { leaf: { $ref: "#/$defs/measure" } } };
      for (let level = 0; level < 60; level += 1) {
        node = {
          type: "object",
          properties: { [`level${level}`]: node, again: { $ref: "#/$defs/measure" } },
        };
      }
      schema.properties.target.properties.risk_detail = node;
    });
    const { catalog } = validateCatalog(deep);
    const target = catalog.contracts
      .find((entry) => entry.id === "quality-evaluation")
      .records.records.find((entry) => entry.type === "target-judgment").shapes[0].shape;
    let node = target.properties.risk_detail;
    for (let level = 59; level >= 0; level -= 1) node = node.properties[`level${level}`];
    assert.deepEqual(Object.keys(node.properties.leaf.properties).sort(), [
      "interpretation",
      "method",
      "metric_id",
      "population",
      "sample_size",
      "task_or_scenario_id",
      "unit",
      "value",
    ]);
  });

