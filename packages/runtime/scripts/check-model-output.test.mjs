/** The real catalog sources, deep-copied so a test can mutate one document. */
function sources() {
  const { readFixture, manifests, readCanonical, keyRegistry, ...documents } =
    readCatalogSources(DEFAULT_REPO_ROOT);
  return { ...structuredClone(documents), readFixture, manifests, readCanonical, keyRegistry };
}

function revisionRules(catalogSources) {
  return catalogSources.rules.find((file) => file.document.family === "revision-accounting")
    .document.rules;
}

function ruleNamed(catalogSources, code) {
  return revisionRules(catalogSources).find((rule) => rule.code === code);
}

function contract(catalogSources) {
  return catalogSources.contracts.find((file) => file.document.id === "authoring-revision")
    .document;
}

