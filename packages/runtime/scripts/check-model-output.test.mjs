/** The failure lines a check refused with; fails when it did not refuse. */
function checkFailures(check) {
  try {
    check();
  } catch (error) {
    assert.ok(Array.isArray(error.failures), error.message);
    return error.failures;
  }
  assert.fail("the check passed");
}

