import { lstat, readFile, realpath, stat } from "node:fs/promises";
import { join, posix, relative, resolve } from "node:path";

import {
  resolveSphinxTargetPath,
  scanSphinxDocument,
  sphinxDocumentCandidatePaths,
  sphinxFormatForPath,
  parseSphinxConfLiterals,
  SphinxStructuralParseError,
  type SphinxConfLiteralsV1,
  type SphinxLocalReferenceV1,
} from "../repository/documentation-source-sphinx.js";

export { SphinxStructuralParseError } from "../repository/documentation-source-sphinx.js";
export type { SphinxStructuralIssueCode } from "../repository/documentation-source-sphinx.js";

export interface SphinxSourceConfigurationFileV1 {
  readonly path: string;
  readonly sha256: string;
}

export interface SphinxSourceChangedPathV1 {
  readonly path: string;
  readonly status: "added" | "modified" | "deleted" | "renamed" | "copied";
}

const CONF_LOCATIONS = ["conf.py", "docs/conf.py"];

/**
 * Walk the toctree/include/literalinclude graph from the conf.py root document,
 * rejecting cycles, path escapes, missing targets, and unsupported directives.
 * Content generated by autodoc/apidoc/autosummary/intersphinx is a limitation.
 */
export async function validateSphinxDocumentationRoot(
  root: string,
  configurationFiles: readonly SphinxSourceConfigurationFileV1[],
  localChanged: readonly SphinxSourceChangedPathV1[],
): Promise<void> {
  const confCandidates = configurationFiles.filter((file) => CONF_LOCATIONS.includes(file.path));
  if (confCandidates.length !== 1)
    throw new SphinxStructuralParseError(
      "Sphinx documentation requires exactly one conf.py at the source root or its docs subdirectory.",
      "ambiguous-configuration-location",
    );
  const confPath = confCandidates[0]!.path;
  const sphinxRoot = posix.dirname(confPath) === "." ? "" : posix.dirname(confPath);
  const confSource = await readSphinxSource(root, confPath);
  const literals = parseSphinxConfLiterals(confSource);

  const rootDocumentBase = joinSphinxPath(sphinxRoot, literals.rootDocument);
  const rootCandidates = sphinxDocumentCandidatePaths(rootDocumentBase, literals.sourceSuffixes);
  const rootDocumentPath = await firstExistingSphinxPath(root, rootCandidates);
  if (!rootDocumentPath)
    throw new SphinxStructuralParseError(
      `Sphinx documentation could not locate a readable root document among: ${rootCandidates.join(", ")}.`,
      "missing-target",
    );

  const visited = new Map<string, "visiting" | "done">();
  const anchors = new Map<string, string>();
  const pendingRefs: Array<{ from: string; reference: SphinxLocalReferenceV1 }> = [];

  await traverseSphinxDocument(
    root,
    sphinxRoot,
    literals,
    rootDocumentPath,
    visited,
    anchors,
    pendingRefs,
  );

  for (const changed of localChanged) {
    if (changed.status === "deleted") continue;
    if (!isSphinxDocumentCandidate(changed.path, literals.sourceSuffixes)) continue;
    if (visited.has(changed.path)) continue;
    await traverseSphinxDocument(
      root,
      sphinxRoot,
      literals,
      changed.path,
      visited,
      anchors,
      pendingRefs,
    );
  }

  for (const pending of pendingRefs) {
    const target = anchors.get(pending.reference.target);
    if (!target)
      throw new SphinxStructuralParseError(
        `Sphinx ref target is missing: ${pending.reference.target} (from ${pending.from}).`,
        "missing-target",
      );
  }
}

async function traverseSphinxDocument(
  root: string,
  sphinxRoot: string,
  literals: SphinxConfLiteralsV1,
  docPath: string,
  visited: Map<string, "visiting" | "done">,
  anchors: Map<string, string>,
  pendingRefs: Array<{ from: string; reference: SphinxLocalReferenceV1 }>,
): Promise<void> {
  const state = visited.get(docPath);
  if (state === "done") return;
  if (state === "visiting")
    throw new SphinxStructuralParseError(
      `Sphinx toctree graph contains a cycle detected while revisiting document: ${docPath}.`,
      "cycle",
    );
  visited.set(docPath, "visiting");
  const source = await readSphinxSource(root, docPath);
  const format = sphinxFormatForPath(docPath);
  const scan = scanSphinxDocument(source, format);
  for (const label of scan.labels) {
    const previous = anchors.get(label.label);
    if (previous && previous !== docPath)
      throw new SphinxStructuralParseError(
        `Sphinx label is defined in more than one document: ${label.label}.`,
        "duplicate-reference-label",
      );
    anchors.set(label.label, docPath);
  }
  for (const directive of scan.directives) {
    if (directive.kind === "toctree") {
      for (const target of directive.targets) {
        const base = resolveSphinxTargetPath(sphinxRoot, docPath, target);
        assertSphinxPathWithinRoot(base, target, sphinxRoot);
        const candidates = sphinxDocumentCandidatePaths(base, literals.sourceSuffixes);
        const resolved = await firstExistingSphinxPath(root, candidates);
        if (!resolved) {
          if (literals.hasGeneratedContentExtension)
            throw new SphinxStructuralParseError(
              `Sphinx toctree target is generated content outside bounded scope: ${base}.`,
              "generated-content-target",
            );
          throw new SphinxStructuralParseError(
            `Sphinx toctree target is missing from the documentation source tree: ${candidates.join(", ")}.`,
            "missing-target",
          );
        }
        await traverseSphinxDocument(
          root,
          sphinxRoot,
          literals,
          resolved,
          visited,
          anchors,
          pendingRefs,
        );
      }
      continue;
    }
    const target = directive.targets[0]!;
    const base = resolveSphinxTargetPath(sphinxRoot, docPath, target);
    assertSphinxPathWithinRoot(base, target, sphinxRoot);
    const exists = await sphinxPathExists(root, base);
    if (!exists)
      throw new SphinxStructuralParseError(
        `Sphinx ${directive.kind} directive target could not be found on disk: ${base}.`,
        "missing-target",
      );
  }
  for (const reference of scan.references) {
    if (reference.role === "doc") {
      const base = resolveSphinxTargetPath(sphinxRoot, docPath, reference.target);
      assertSphinxPathWithinRoot(base, reference.target, sphinxRoot);
      const candidates = sphinxDocumentCandidatePaths(base, literals.sourceSuffixes);
      const resolved = await firstExistingSphinxPath(root, candidates);
      if (!resolved)
        throw new SphinxStructuralParseError(
          `Sphinx doc reference target is missing: ${candidates.join(", ")}.`,
          "missing-target",
        );
      continue;
    }
    pendingRefs.push({ from: docPath, reference });
  }
  visited.set(docPath, "done");
}

function joinSphinxPath(base: string, target: string): string {
  return base ? `${base}/${target}` : target;
}

function isSphinxDocumentCandidate(path: string, suffixes: readonly string[]): boolean {
  return suffixes.some((suffix) => path.toLowerCase().endsWith(suffix.toLowerCase()));
}

function assertSphinxPathWithinRoot(
  candidate: string,
  rawTarget: string,
  sphinxRoot: string,
): void {
  const escapesRepositoryRoot =
    candidate === ".." || candidate.startsWith("../") || candidate.startsWith("/");
  const escapesSphinxSourceRoot =
    !escapesRepositoryRoot &&
    sphinxRoot !== "" &&
    candidate !== sphinxRoot &&
    !candidate.startsWith(`${sphinxRoot}/`);
  if (escapesRepositoryRoot || escapesSphinxSourceRoot)
    throw new SphinxStructuralParseError(
      `Sphinx target escapes the documentation source root: ${rawTarget}.`,
      "path-escape",
    );
}

async function readSphinxSource(root: string, path: string): Promise<string> {
  const absolute = await resolveSafeSphinxAbsolutePath(root, path);
  try {
    return await readFile(absolute, "utf8");
  } catch {
    throw new SphinxStructuralParseError(
      `Sphinx documentation source file could not be read from disk: ${path}.`,
      "missing-target",
    );
  }
}

async function sphinxPathExists(root: string, path: string): Promise<boolean> {
  const absolute = await resolveSafeSphinxAbsolutePath(root, path);
  try {
    return (await stat(absolute)).isFile();
  } catch {
    return false;
  }
}

async function firstExistingSphinxPath(
  root: string,
  candidates: readonly string[],
): Promise<string | undefined> {
  for (const candidate of candidates) {
    if (await sphinxPathExists(root, candidate)) return candidate;
  }
  return undefined;
}

async function resolveSafeSphinxAbsolutePath(root: string, path: string): Promise<string> {
  const absolute = resolve(root, ...path.split("/"));
  if (!withinSphinxRoot(root, absolute))
    throw new SphinxStructuralParseError(
      `Sphinx target escapes the documentation source root: ${path}.`,
      "path-escape",
    );
  let current = root;
  for (const segment of path.split("/").filter(Boolean)) {
    current = join(current, segment);
    let info;
    try {
      info = await lstat(current);
    } catch {
      return absolute;
    }
    if (info.isSymbolicLink())
      throw new SphinxStructuralParseError(
        `Sphinx target path traverses an unsafe symbolic link segment: ${path}.`,
        "path-escape",
      );
  }
  const rootReal = await realpath(root);
  const valueReal = await realpath(absolute);
  if (!withinSphinxRoot(rootReal, valueReal))
    throw new SphinxStructuralParseError(
      `Sphinx target escapes the documentation source root: ${path}.`,
      "path-escape",
    );
  return absolute;
}

function withinSphinxRoot(root: string, value: string): boolean {
  const result = relative(root, value);
  return (
    result === "" ||
    (!result.startsWith("..") && !result.includes("../") && !result.includes("..\\"))
  );
}
