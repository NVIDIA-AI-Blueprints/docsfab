/**
 * Unified diff adapter for `.diff` and `.patch` originals: `git diff` and
 * `git show` output, `git format-patch` patches and mbox series, `--no-prefix`
 * diffs, and plain `diff -u` and `diff -ruN` output.
 *
 * The derivative opens with a host-written manifest of every file. Every other
 * span is a verbatim slice of the original, line terminators and carriage
 * returns included, except that a span's final newline is the host separator
 * that follows it; its `diff` locator names that slice's byte range. Text in no
 * span: a Git binary patch's encoded payload; a hunk body, file body, note, or
 * message that is not UTF-8; and a run of empty lines outside any file. The
 * first two are recorded as `non-text-content-excluded` and named in the
 * manifest. A file header line that is not UTF-8 is framing the adapter cannot
 * walk, and it records `unsupported-encoding`.
 */
