import { readFile, readdir } from "node:fs/promises";
import { relative, resolve } from "node:path";

const MAX_DOCUSAURUS_SOURCE_BYTES = 1024 * 1024;
const DOUBLE_QUOTE = String.fromCharCode(34);
const SINGLE_QUOTE = String.fromCharCode(39);

/** Stable, content-free reason a Docusaurus literal source fell outside the supported grammar. */
export class DocusaurusStructuralParseError extends Error {
  public constructor(message: string) {
    super(message);
    this.name = "DocusaurusStructuralParseError";
  }
}

export type DocusaurusLiteralValue =
  | Readonly<{ kind: "string"; value: string }>
  | Readonly<{ kind: "number"; value: number }>
  | Readonly<{ kind: "boolean"; value: boolean }>
  | Readonly<{ kind: "null" }>
  | Readonly<{ kind: "array"; items: readonly DocusaurusLiteralValue[] }>
  | Readonly<{
      kind: "object";
      entries: readonly Readonly<{ key: string; value: DocusaurusLiteralValue }>[];
    }>;

export const DOCUSAURUS_SIDEBAR_ITEM_TYPES = ["doc", "category", "autogenerated", "link"] as const;
export type DocusaurusSidebarItemType = (typeof DOCUSAURUS_SIDEBAR_ITEM_TYPES)[number];

export type DocusaurusSidebarItem =
  | Readonly<{ type: "doc"; id: string }>
  | Readonly<{ type: "category"; label: string; items: readonly DocusaurusSidebarItem[] }>
  | Readonly<{ type: "autogenerated"; dirName: string }>
  | Readonly<{ type: "link"; label: string; href: string }>;

export type DocusaurusSidebarsV1 = Readonly<Record<string, readonly DocusaurusSidebarItem[]>>;

type TokenType = "punct" | "ident" | "string" | "number" | "eof";
interface Token {
  readonly type: TokenType;
  readonly value: string;
}
interface ParserState {
  readonly tokens: readonly Token[];
  pos: number;
}

const PUNCTUATION = new Set(["{", "}", "[", "]", "(", ")", ":", ",", ";", "=", ".", "*"]);

/**
 * Tokenize the literal JS/TS subset of Docusaurus config and sidebars files
 * without evaluating anything; unsupported characters fail closed.
 */
function tokenize(source: string): Token[] {
  if (source.length > MAX_DOCUSAURUS_SOURCE_BYTES)
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration source exceeds the bounded supported parse size limit.",
    );
  const tokens: Token[] = [];
  let index = 0;
  const length = source.length;
  while (index < length) {
    const character = source[index] ?? "";
    if (/\s/u.test(character)) {
      index += 1;
      continue;
    }
    if (character === "/" && source[index + 1] === "/") {
      while (index < length && source[index] !== "\n") index += 1;
      continue;
    }
    if (character === "/" && source[index + 1] === "*") {
      const end = source.indexOf("*/", index + 2);
      if (end < 0)
        throw new DocusaurusStructuralParseError(
          "Docusaurus configuration contains an unterminated block comment here.",
        );
      index = end + 2;
      continue;
    }
    if (character === DOUBLE_QUOTE || character === SINGLE_QUOTE) {
      const { value, next } = readQuotedString(source, index, character);
      tokens.push({ type: "string", value });
      index = next;
      continue;
    }
    if (character === "`") {
      const { value, next } = readTemplateString(source, index);
      tokens.push({ type: "string", value });
      index = next;
      continue;
    }
    if (/[0-9]/u.test(character)) {
      let cursor = index;
      while (cursor < length && /[0-9.]/u.test(source[cursor] ?? "")) cursor += 1;
      tokens.push({ type: "number", value: source.slice(index, cursor) });
      index = cursor;
      continue;
    }
    if (/[A-Za-z_$]/u.test(character)) {
      let cursor = index;
      while (cursor < length && /[A-Za-z0-9_$]/u.test(source[cursor] ?? "")) cursor += 1;
      tokens.push({ type: "ident", value: source.slice(index, cursor) });
      index = cursor;
      continue;
    }
    if (character === "." && source[index + 1] === "." && source[index + 2] === ".") {
      tokens.push({ type: "punct", value: "..." });
      index += 3;
      continue;
    }
    if (PUNCTUATION.has(character)) {
      tokens.push({ type: "punct", value: character });
      index += 1;
      continue;
    }
    throw new DocusaurusStructuralParseError(
      `Docusaurus configuration contains an unsupported character token: ${JSON.stringify(character)}.`,
    );
  }
  tokens.push({ type: "eof", value: "" });
  return tokens;
}

function readQuotedString(
  source: string,
  start: number,
  quote: string,
): { value: string; next: number } {
  let cursor = start + 1;
  let value = "";
  while (cursor < source.length && source[cursor] !== quote) {
    if (source[cursor] === "\\") {
      value += unescapeCharacter(source[cursor + 1] ?? "");
      cursor += 2;
      continue;
    }
    value += source[cursor];
    cursor += 1;
  }
  if (cursor >= source.length)
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration contains an unterminated quoted string literal.",
    );
  return { value, next: cursor + 1 };
}

function readTemplateString(source: string, start: number): { value: string; next: number } {
  let cursor = start + 1;
  let value = "";
  let interpolated = false;
  while (cursor < source.length && source[cursor] !== "`") {
    if (source[cursor] === "\\") {
      value += unescapeCharacter(source[cursor + 1] ?? "");
      cursor += 2;
      continue;
    }
    if (source[cursor] === "$" && source[cursor + 1] === "{") interpolated = true;
    value += source[cursor];
    cursor += 1;
  }
  if (cursor >= source.length)
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration contains an unterminated template string literal.",
    );
  if (interpolated)
    throw new DocusaurusStructuralParseError(
      "Docusaurus template literal expressions are not part of the supported literal grammar.",
    );
  return { value, next: cursor + 1 };
}

function unescapeCharacter(character: string): string {
  if (character === "n") return "\n";
  if (character === "t") return "\t";
  if (character === "r") return "\r";
  return character;
}

function peek(state: ParserState): Token {
  return state.tokens[state.pos] ?? { type: "eof", value: "" };
}

function advance(state: ParserState): Token {
  const token = peek(state);
  state.pos += 1;
  return token;
}

function isPunct(token: Token, value: string): boolean {
  return token.type === "punct" && token.value === value;
}

function isIdent(token: Token, value: string): boolean {
  return token.type === "ident" && token.value === value;
}

function expectPunct(state: ParserState, value: string): void {
  const token = advance(state);
  if (!isPunct(token, value))
    throw new DocusaurusStructuralParseError(
      `Docusaurus configuration is missing the required "${value}" token here.`,
    );
}

function consumeOptionalSemicolon(state: ParserState): void {
  if (isPunct(peek(state), ";")) advance(state);
}

/** Skip a `: Type` annotation up to the top-level assignment token. */
function skipTypeAnnotation(state: ParserState): void {
  advance(state); // ":"
  let depth = 0;
  while (true) {
    const token = peek(state);
    if (token.type === "eof")
      throw new DocusaurusStructuralParseError(
        "Docusaurus type annotation never reaches its terminating assignment token.",
      );
    if (token.type === "punct" && "({[".includes(token.value)) depth += 1;
    if (token.type === "punct" && ")}]".includes(token.value)) depth -= 1;
    if (depth === 0 && isPunct(token, "=")) return;
    advance(state);
  }
}

/** Skip a type-only `type X = ...;` alias statement. Assumes "type" is the next token. */
function skipTypeAliasStatement(state: ParserState): void {
  advance(state); // "type"
  let depth = 0;
  while (true) {
    const token = peek(state);
    if (token.type === "eof") return;
    if (token.type === "punct" && "({[".includes(token.value)) depth += 1;
    if (token.type === "punct" && ")}]".includes(token.value)) depth -= 1;
    if (depth === 0 && isPunct(token, ";")) {
      advance(state);
      return;
    }
    advance(state);
  }
}

/** Skip a type-only `interface X { ... }` declaration. Assumes "interface" is next. */
function skipInterfaceStatement(state: ParserState): void {
  advance(state); // "interface"
  while (!isPunct(peek(state), "{")) {
    if (peek(state).type === "eof")
      throw new DocusaurusStructuralParseError(
        "Docusaurus interface declaration never reaches its opening brace body.",
      );
    advance(state);
  }
  let depth = 0;
  do {
    const token = advance(state);
    if (isPunct(token, "{")) depth += 1;
    if (isPunct(token, "}")) depth -= 1;
  } while (depth > 0);
}

/** Consume a type-only import, or record a value-import local names as foreign. */
function parseImportStatement(state: ParserState, foreignNames: Set<string>): void {
  advance(state); // "import"
  if (isIdent(peek(state), "type")) {
    skipTypeAliasLikeImport(state);
    return;
  }
  const names: string[] = [];
  let sawNonTypeBinding = false;
  const next = peek(state);
  if (next.type === "ident") {
    names.push(next.value);
    sawNonTypeBinding = true;
    advance(state);
    if (isPunct(peek(state), ",")) advance(state);
  }
  if (isPunct(peek(state), "*")) {
    advance(state);
    if (!isIdent(peek(state), "as"))
      throw new DocusaurusStructuralParseError(
        "Docusaurus namespace imports must use the supported as-binding syntax.",
      );
    advance(state);
    const namespaceName = advance(state);
    if (namespaceName.type !== "ident")
      throw new DocusaurusStructuralParseError(
        "Docusaurus namespace import bindings must declare a plain identifier name.",
      );
    names.push(namespaceName.value);
    sawNonTypeBinding = true;
  } else if (isPunct(peek(state), "{")) {
    advance(state);
    while (!isPunct(peek(state), "}")) {
      let isType = false;
      if (isIdent(peek(state), "type")) {
        isType = true;
        advance(state);
      }
      const specifier = advance(state);
      if (specifier.type !== "ident")
        throw new DocusaurusStructuralParseError(
          "Docusaurus named import specifiers must be plain identifier names.",
        );
      let localName = specifier.value;
      if (isIdent(peek(state), "as")) {
        advance(state);
        const alias = advance(state);
        if (alias.type !== "ident")
          throw new DocusaurusStructuralParseError(
            "Docusaurus import aliases must rename to a plain identifier name.",
          );
        localName = alias.value;
      }
      if (!isType) {
        sawNonTypeBinding = true;
        names.push(localName);
      }
      if (isPunct(peek(state), ",")) {
        advance(state);
        continue;
      }
      break;
    }
    expectPunct(state, "}");
  }
  if (!isIdent(peek(state), "from"))
    throw new DocusaurusStructuralParseError(
      "Docusaurus import statements must specify a following from clause.",
    );
  advance(state);
  const moduleToken = advance(state);
  if (moduleToken.type !== "string")
    throw new DocusaurusStructuralParseError(
      "Docusaurus import module specifiers must be a plain string literal.",
    );
  consumeOptionalSemicolon(state);
  if (sawNonTypeBinding) for (const name of names) foreignNames.add(name);
}

/**
 * Stop right after the `import type` module specifier and an optional
 * semicolon, so a no-semicolon file does not swallow the export that follows.
 */
function skipTypeAliasLikeImport(state: ParserState): void {
  advance(state); // "type"
  const next = peek(state);
  if (next.type === "ident") {
    advance(state);
  } else if (isPunct(next, "*")) {
    advance(state);
    if (!isIdent(peek(state), "as"))
      throw new DocusaurusStructuralParseError(
        "Docusaurus namespace imports must use the supported as-binding syntax.",
      );
    advance(state);
    const namespaceName = advance(state);
    if (namespaceName.type !== "ident")
      throw new DocusaurusStructuralParseError(
        "Docusaurus namespace import bindings must declare a plain identifier name.",
      );
  } else if (isPunct(next, "{")) {
    advance(state);
    while (!isPunct(peek(state), "}")) {
      if (peek(state).type === "eof")
        throw new DocusaurusStructuralParseError(
          "Docusaurus type-only import specifier list never reaches its closing brace.",
        );
      advance(state);
    }
    advance(state);
  } else {
    throw new DocusaurusStructuralParseError(
      "Docusaurus type-only import statement has an unsupported binding shape.",
    );
  }
  if (!isIdent(peek(state), "from"))
    throw new DocusaurusStructuralParseError(
      "Docusaurus type-only import statements must specify a following from clause.",
    );
  advance(state);
  const moduleToken = advance(state);
  if (moduleToken.type !== "string")
    throw new DocusaurusStructuralParseError(
      "Docusaurus type-only import module specifiers must be a plain string literal.",
    );
  consumeOptionalSemicolon(state);
}

function parseLiteralValue(
  state: ParserState,
  locals: ReadonlyMap<string, DocusaurusLiteralValue>,
  foreignNames: ReadonlySet<string>,
): DocusaurusLiteralValue {
  const token = peek(state);
  if (token.type === "string") {
    advance(state);
    return { kind: "string", value: token.value };
  }
  if (token.type === "number") {
    advance(state);
    return { kind: "number", value: Number(token.value) };
  }
  if (isPunct(token, "-")) {
    advance(state);
    const next = advance(state);
    if (next.type !== "number")
      throw new DocusaurusStructuralParseError(
        "Docusaurus numeric literals only support one simple leading minus sign.",
      );
    return { kind: "number", value: -Number(next.value) };
  }
  if (isIdent(token, "true")) {
    advance(state);
    return { kind: "boolean", value: true };
  }
  if (isIdent(token, "false")) {
    advance(state);
    return { kind: "boolean", value: false };
  }
  if (isIdent(token, "null")) {
    advance(state);
    return { kind: "null" };
  }
  if (isIdent(token, "undefined"))
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration values must be literal, not the undefined keyword.",
    );
  if (isPunct(token, "[")) return parseArrayLiteral(state, locals, foreignNames);
  if (isPunct(token, "{")) return parseObjectLiteral(state, locals, foreignNames);
  if (isPunct(token, "..."))
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration values cannot use spread syntax here.",
    );
  if (token.type === "ident") {
    advance(state);
    const name = token.value;
    if (isPunct(peek(state), "("))
      throw new DocusaurusStructuralParseError(
        "Docusaurus configuration values cannot invoke a function call expression.",
      );
    if (isPunct(peek(state), "."))
      throw new DocusaurusStructuralParseError(
        "Docusaurus configuration values cannot use a property access member expression.",
      );
    if (foreignNames.has(name))
      throw new DocusaurusStructuralParseError(
        `Docusaurus configuration references an unresolved imported runtime identifier: ${name}.`,
      );
    const resolved = locals.get(name);
    if (!resolved)
      throw new DocusaurusStructuralParseError(
        `Docusaurus configuration references an undeclared local identifier: ${name}.`,
      );
    return resolved;
  }
  throw new DocusaurusStructuralParseError(
    "Docusaurus configuration contains a value outside the supported literal grammar.",
  );
}

function parseArrayLiteral(
  state: ParserState,
  locals: ReadonlyMap<string, DocusaurusLiteralValue>,
  foreignNames: ReadonlySet<string>,
): DocusaurusLiteralValue {
  advance(state); // "["
  const items: DocusaurusLiteralValue[] = [];
  while (!isPunct(peek(state), "]")) {
    if (isPunct(peek(state), "..."))
      throw new DocusaurusStructuralParseError(
        "Docusaurus array literals cannot contain a spread syntax element.",
      );
    items.push(parseLiteralValue(state, locals, foreignNames));
    if (isPunct(peek(state), ",")) {
      advance(state);
      continue;
    }
    break;
  }
  expectPunct(state, "]");
  return { kind: "array", items: Object.freeze(items) };
}

function parseObjectLiteral(
  state: ParserState,
  locals: ReadonlyMap<string, DocusaurusLiteralValue>,
  foreignNames: ReadonlySet<string>,
): DocusaurusLiteralValue {
  advance(state); // "{"
  const entries: Readonly<{ key: string; value: DocusaurusLiteralValue }>[] = [];
  const seenKeys = new Set<string>();
  while (!isPunct(peek(state), "}")) {
    const token = peek(state);
    if (isPunct(token, "..."))
      throw new DocusaurusStructuralParseError(
        "Docusaurus object literals cannot contain a spread syntax property.",
      );
    if (isPunct(token, "["))
      throw new DocusaurusStructuralParseError(
        "Docusaurus object literals cannot use a computed property key expression.",
      );
    let key: string;
    if (token.type === "string" || token.type === "ident") {
      key = token.value;
      advance(state);
    } else
      throw new DocusaurusStructuralParseError(
        "Docusaurus object literal keys must be identifiers or plain string literals.",
      );
    if (!isPunct(peek(state), ":"))
      throw new DocusaurusStructuralParseError(
        "Docusaurus object literal shorthand properties are not part of the supported grammar.",
      );
    advance(state); // ":"
    const value = parseLiteralValue(state, locals, foreignNames);
    if (seenKeys.has(key))
      throw new DocusaurusStructuralParseError(
        `Docusaurus object literal repeats the same property key twice: ${key}.`,
      );
    seenKeys.add(key);
    entries.push({ key, value });
    if (isPunct(peek(state), ",")) {
      advance(state);
      continue;
    }
    break;
  }
  expectPunct(state, "}");
  return { kind: "object", entries: Object.freeze(entries) };
}

/**
 * Parse the `module.exports` / `export default` / one local literal binding
 * grammar without evaluation. Calls, spreads, computed keys, and value imports
 * referenced by the exported value are rejected.
 */
export function parseDocusaurusLiteralModule(source: string): DocusaurusLiteralValue {
  const state: ParserState = { tokens: tokenize(source), pos: 0 };
  const locals = new Map<string, DocusaurusLiteralValue>();
  const foreignNames = new Set<string>();
  let localBindingName: string | undefined;
  let exported: DocusaurusLiteralValue | undefined;

  while (peek(state).type !== "eof") {
    const token = peek(state);
    if (isIdent(token, "import")) {
      parseImportStatement(state, foreignNames);
      continue;
    }
    if (isIdent(token, "interface")) {
      skipInterfaceStatement(state);
      continue;
    }
    if (isIdent(token, "type")) {
      skipTypeAliasStatement(state);
      continue;
    }
    if (isIdent(token, "export")) {
      advance(state); // "export"
      const next = peek(state);
      if (isIdent(next, "default")) {
        advance(state);
        if (exported !== undefined)
          throw new DocusaurusStructuralParseError(
            "Docusaurus configuration supports only one governing export statement total.",
          );
        exported = parseLiteralValue(state, locals, foreignNames);
        consumeOptionalSemicolon(state);
        continue;
      }
      if (isIdent(next, "type")) {
        skipTypeAliasStatement(state);
        continue;
      }
      if (isIdent(next, "interface")) {
        skipInterfaceStatement(state);
        continue;
      }
      throw new DocusaurusStructuralParseError(
        "Docusaurus configuration only supports a default export statement here.",
      );
    }
    if (isIdent(token, "const")) {
      if (localBindingName !== undefined)
        throw new DocusaurusStructuralParseError(
          "Docusaurus configuration supports only one local literal constant binding.",
        );
      advance(state); // "const"
      const nameToken = advance(state);
      if (nameToken.type !== "ident")
        throw new DocusaurusStructuralParseError(
          "Docusaurus local constant bindings must declare a plain identifier name.",
        );
      localBindingName = nameToken.value;
      if (isPunct(peek(state), ":")) skipTypeAnnotation(state);
      if (!isPunct(peek(state), "="))
        throw new DocusaurusStructuralParseError(
          "Docusaurus local constant bindings must assign a literal value directly.",
        );
      advance(state); // "="
      const value = parseLiteralValue(state, locals, foreignNames);
      locals.set(localBindingName, value);
      consumeOptionalSemicolon(state);
      continue;
    }
    if (isIdent(token, "module")) {
      advance(state); // "module"
      expectPunct(state, ".");
      const property = advance(state);
      if (property.type !== "ident" || property.value !== "exports")
        throw new DocusaurusStructuralParseError(
          "Docusaurus configuration only supports assigning module.exports directly here.",
        );
      if (!isPunct(peek(state), "="))
        throw new DocusaurusStructuralParseError(
          "Docusaurus module.exports assignment requires a following equals sign token.",
        );
      advance(state); // "="
      if (exported !== undefined)
        throw new DocusaurusStructuralParseError(
          "Docusaurus configuration supports only one governing export statement total.",
        );
      exported = parseLiteralValue(state, locals, foreignNames);
      consumeOptionalSemicolon(state);
      continue;
    }
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration contains an unsupported top-level statement form.",
    );
  }

  if (exported === undefined)
    throw new DocusaurusStructuralParseError(
      "Docusaurus configuration must assign module.exports or export default.",
    );
  return exported;
}

export function parseDocusaurusSidebars(source: string): DocusaurusSidebarsV1 {
  const value = parseDocusaurusLiteralModule(source);
  if (value.kind === "array") return Object.freeze({ default: toSidebarItems(value.items) });
  if (value.kind === "object") {
    const result: Record<string, readonly DocusaurusSidebarItem[]> = {};
    for (const entry of value.entries) {
      if (entry.value.kind !== "array")
        throw new DocusaurusStructuralParseError(
          `Docusaurus sidebar entry must be declared as a literal array: ${entry.key}.`,
        );
      result[entry.key] = toSidebarItems(entry.value.items);
    }
    return Object.freeze(result);
  }
  throw new DocusaurusStructuralParseError(
    "Docusaurus sidebars module must export a literal object or array value.",
  );
}

function toSidebarItems(
  items: readonly DocusaurusLiteralValue[],
): readonly DocusaurusSidebarItem[] {
  return Object.freeze(items.map(toSidebarItem));
}

function toSidebarItem(value: DocusaurusLiteralValue): DocusaurusSidebarItem {
  if (value.kind === "string") return { type: "doc", id: value.value };
  if (value.kind !== "object")
    throw new DocusaurusStructuralParseError(
      "Docusaurus sidebar items must be a literal string or object value.",
    );
  const fields = new Map(value.entries.map((entry) => [entry.key, entry.value]));
  const typeField = fields.get("type");
  const type = typeField && typeField.kind === "string" ? typeField.value : "doc";
  if (type === "doc") {
    const id = fields.get("id");
    if (!id || id.kind !== "string")
      throw new DocusaurusStructuralParseError(
        "Docusaurus doc sidebar items require a literal string id field.",
      );
    return { type: "doc", id: id.value };
  }
  if (type === "category") {
    const label = fields.get("label");
    const items = fields.get("items");
    if (!label || label.kind !== "string")
      throw new DocusaurusStructuralParseError(
        "Docusaurus category sidebar items require a literal string label field.",
      );
    if (!items || items.kind !== "array")
      throw new DocusaurusStructuralParseError(
        "Docusaurus category sidebar items require a literal items array field.",
      );
    return { type: "category", label: label.value, items: toSidebarItems(items.items) };
  }
  if (type === "autogenerated") {
    const dirName = fields.get("dirName");
    if (!dirName || dirName.kind !== "string")
      throw new DocusaurusStructuralParseError(
        "Docusaurus autogenerated sidebar items require a literal dirName field.",
      );
    return { type: "autogenerated", dirName: dirName.value };
  }
  if (type === "link") {
    const label = fields.get("label");
    const href = fields.get("href");
    if (!label || label.kind !== "string" || !href || href.kind !== "string")
      throw new DocusaurusStructuralParseError(
        "Docusaurus link sidebar items require literal label and href fields both.",
      );
    return { type: "link", label: label.value, href: href.value };
  }
  throw new DocusaurusStructuralParseError(
    `Docusaurus sidebar item declares an unsupported item type: ${type}.`,
  );
}

export function docusaurusSidebarDocIds(sidebars: DocusaurusSidebarsV1): readonly string[] {
  const ids = new Set<string>();
  const visit = (items: readonly DocusaurusSidebarItem[]): void => {
    for (const item of items) {
      if (item.type === "doc") ids.add(item.id);
      else if (item.type === "category") visit(item.items);
    }
  };
  for (const items of Object.values(sidebars)) visit(items);
  return Object.freeze([...ids]);
}

export function docusaurusSidebarAutogeneratedDirs(
  sidebars: DocusaurusSidebarsV1,
): readonly string[] {
  const dirs = new Set<string>();
  const visit = (items: readonly DocusaurusSidebarItem[]): void => {
    for (const item of items) {
      if (item.type === "autogenerated") dirs.add(item.dirName);
      else if (item.type === "category") visit(item.items);
    }
  };
  for (const items of Object.values(sidebars)) visit(items);
  return Object.freeze([...dirs]);
}

/** The default Docusaurus doc id is its docs-root-relative path without extension. */
export function docusaurusDefaultDocId(docsRootRelativePath: string): string {
  return docsRootRelativePath.replace(/\.mdx?$/u, "");
}

/** Extract the bounded `id`/`slug` frontmatter scalars used for doc identity. */
export function docusaurusFrontmatterIdentity(
  source: string,
): Readonly<{ id?: string; slug?: string }> {
  const lines = source.split(/\r?\n/u);
  if ((lines[0] ?? "").trim() !== "---") return Object.freeze({});
  const closing = lines.slice(1).findIndex((line) => /^(?:---|\.\.\.)\s*$/u.test(line.trim()));
  if (closing < 0) return Object.freeze({});
  const block = lines.slice(1, closing + 1);
  let id: string | undefined;
  let slug: string | undefined;
  for (const line of block) {
    const idMatch = /^id:\s*[\x27"]?([^\x27"#]+?)[\x27"]?\s*$/u.exec(line);
    if (idMatch?.[1]) id = idMatch[1].trim();
    const slugMatch = /^slug:\s*[\x27"]?([^\x27"#]+?)[\x27"]?\s*$/u.exec(line);
    if (slugMatch?.[1]) slug = slugMatch[1].trim();
  }
  return Object.freeze({ id, slug });
}

/**
 * Resolve documents reachable by explicit doc id (frontmatter id, else the
 * path-derived id) or autogenerated directory. A missing docs root yields an
 * empty set rather than failing closed here.
 */
export async function docusaurusReachableDocumentPaths(
  root: string,
  docsDirectory: string,
  sidebars: DocusaurusSidebarsV1,
): Promise<ReadonlySet<string>> {
  const docsRoot = resolve(root, docsDirectory);
  const reachable = new Set<string>();
  const docIds = new Set(docusaurusSidebarDocIds(sidebars));
  const autogeneratedDirs = docusaurusSidebarAutogeneratedDirs(sidebars);
  const documents = await collectDocusaurusMarkdownFiles(docsRoot);
  for (const absolute of documents) {
    const relativeToDocs = relative(docsRoot, absolute).replaceAll("\\", "/");
    const defaultId = docusaurusDefaultDocId(relativeToDocs);
    let frontmatterId: string | undefined;
    try {
      frontmatterId = docusaurusFrontmatterIdentity(await readFile(absolute, "utf8")).id;
    } catch {
      frontmatterId = undefined;
    }
    const id = frontmatterId ?? defaultId;
    if (docIds.has(id)) {
      reachable.add(absolute);
      continue;
    }
    for (const dirName of autogeneratedDirs) {
      if (
        dirName === "." ||
        relativeToDocs === dirName ||
        relativeToDocs.startsWith(`${dirName}/`)
      ) {
        reachable.add(absolute);
        break;
      }
    }
  }
  return reachable;
}

async function collectDocusaurusMarkdownFiles(directory: string): Promise<string[]> {
  let entries;
  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch {
    return [];
  }
  const files: string[] = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectDocusaurusMarkdownFiles(path)));
    else if (entry.isFile() && /\.mdx?$/u.test(entry.name)) files.push(path);
  }
  return files;
}
