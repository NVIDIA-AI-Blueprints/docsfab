import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { describe, expect, it } from "vitest";

import {
  createDocumentationSourceApplicability,
  deriveDocumentationSourceApplicability,
  type DocumentationChangedPathStatus,
} from "../src/repository/documentation-source-applicability.js";
import { DOCUMENTATION_SOURCE_ADAPTER_VERSION } from "../src/repository/documentation-source-support.js";
import {
  docusaurusDefaultDocId,
  docusaurusFrontmatterIdentity,
  docusaurusReachableDocumentPaths,
  docusaurusSidebarAutogeneratedDirs,
  docusaurusSidebarDocIds,
  parseDocusaurusLiteralModule,
  parseDocusaurusSidebars,
} from "../src/repository/documentation-source-docusaurus.js";
import { validateSourceAwareStructuralDocumentation } from "../src/delivery/structural-documentation-validator.js";
import { temporaryRoots } from "./helpers/temp.js";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURE_ROOT = resolve(projectRoot, "test/fixtures/documentation-sources/docusaurus");
const TS_FIXTURE_ROOT = resolve(
  projectRoot,
  "test/fixtures/documentation-sources/docusaurus-typescript",
);

const roots = temporaryRoots();

function sha256(value: string): string {
  return createHash("sha256").update(value).digest("hex");
}

async function buildDocusaurusApplicability(options: {
  root: string;
  changedPaths: readonly { path: string; status: DocumentationChangedPathStatus }[];
  configurationFiles?: readonly string[];
}) {
  const configurationPaths = [
    ...(options.configurationFiles ?? ["docusaurus.config.js", "sidebars.js"]),
  ].sort();
  const configurationFiles = await Promise.all(
    configurationPaths.map(async (path) => ({
      path,
      sha256: sha256(await readFile(join(options.root, path), "utf8")),
    })),
  );
  return createDocumentationSourceApplicability({
    repositoryIdentitySha256: sha256("repository"),
    baseRevision: "a".repeat(40),
    candidateInputTreeSha256: sha256("candidate"),
    changedPaths: options.changedPaths,
    roots: [
      {
        root: ".",
        adapterId: "docusaurus",
        adapterVersion: DOCUMENTATION_SOURCE_ADAPTER_VERSION,
        configurationFiles,
        navigationMode: "explicit",
        requiredPathClosureSha256: sha256("closure"),
        limitations: [],
      },
    ],
  });
}

describe("Docusaurus documentation source adapter", () => {
  it("parses literal module.exports sidebars with nested categories, autogenerated dirs, doc ids, and link items", async () => {
    const source = await readFile(join(FIXTURE_ROOT, "sidebars.js"), "utf8");
    const sidebars = parseDocusaurusSidebars(source);
    expect(sidebars).toEqual({
      tutorialSidebar: [
        { type: "doc", id: "intro" },
        { type: "doc", id: "getting-started" },
        {
          type: "category",
          label: "Guides",
          items: [{ type: "autogenerated", dirName: "guides" }],
        },
        { type: "link", label: "Project Home", href: "https://example.invalid/repo" },
      ],
    });
    expect(docusaurusSidebarDocIds(sidebars)).toEqual(["intro", "getting-started"]);
    expect(docusaurusSidebarAutogeneratedDirs(sidebars)).toEqual(["guides"]);
  });

  it("parses export default with a type-only import, a type annotation, and one local literal binding", async () => {
    const source = await readFile(join(TS_FIXTURE_ROOT, "sidebars.ts"), "utf8");
    const sidebars = parseDocusaurusSidebars(source);
    expect(sidebars).toEqual({
      tutorialSidebar: [
        { type: "doc", id: "intro" },
        {
          type: "category",
          label: "Reference",
          items: [
            { type: "doc", id: "reference/one" },
            { type: "doc", id: "reference/two" },
          ],
        },
      ],
    });
  });

  it("parses both single-quoted and double-quoted string literals", () => {
    const q = String.fromCharCode(39);
    const source = [
      "module.exports = {",
      `  tutorialSidebar: [${q}intro${q}, ${q}guide${q}],`,
      "};",
    ].join("\n");
    expect(parseDocusaurusSidebars(source)).toEqual({
      tutorialSidebar: [
        { type: "doc", id: "intro" },
        { type: "doc", id: "guide" },
      ],
    });
  });

  it("rejects a function call expression in the exported value", () => {
    expect(() => parseDocusaurusLiteralModule('module.exports = require("./generated");')).toThrow(
      /function call expression/u,
    );
  });

  it("rejects spread syntax inside an array literal", () => {
    expect(() =>
      parseDocusaurusLiteralModule("module.exports = { tutorialSidebar: [...extra] };"),
    ).toThrow(/spread syntax/u);
  });

  it("rejects a computed object property key", () => {
    expect(() => parseDocusaurusLiteralModule("module.exports = { [dynamicKey]: [] };")).toThrow(
      /computed property key/u,
    );
  });

  it("rejects a referenced non-type-only runtime import", () => {
    const source = ['import shared from "./shared-sidebar";', "module.exports = shared;"].join(
      "\n",
    );
    expect(() => parseDocusaurusLiteralModule(source)).toThrow(/imported runtime identifier/u);
  });

  it("accepts an unreferenced non-type-only import without evaluating it", () => {
    const source = [
      'import unused from "./unused";',
      'module.exports = { tutorialSidebar: ["intro"] };',
    ].join("\n");
    expect(() => parseDocusaurusLiteralModule(source)).not.toThrow();
  });

  it("rejects more than one local literal constant binding", () => {
    const source = [
      'const a = ["intro"];',
      'const b = ["guide"];',
      "module.exports = { tutorialSidebar: a };",
    ].join("\n");
    expect(() => parseDocusaurusLiteralModule(source)).toThrow(
      /only one local literal constant binding/u,
    );
  });

  it("rejects a source with no module.exports or export default statement", () => {
    expect(() => parseDocusaurusLiteralModule("const sidebars = { tutorialSidebar: [] };")).toThrow(
      /must assign module.exports or export default/u,
    );
  });

  it("rejects an unsupported sidebar item type", () => {
    const source = 'module.exports = { tutorialSidebar: [{ type: "ref", id: "intro" }] };';
    expect(() => parseDocusaurusSidebars(source)).toThrow(/unsupported item type/u);
  });

  it("extracts frontmatter id and slug, returning none for a body without frontmatter", () => {
    const withFrontmatter = [
      "---",
      "id: getting-started",
      "slug: /start",
      "---",
      "",
      "# Body",
      "",
    ].join("\n");
    expect(docusaurusFrontmatterIdentity(withFrontmatter)).toEqual({
      id: "getting-started",
      slug: "/start",
    });
    expect(docusaurusFrontmatterIdentity("# No frontmatter\n")).toEqual({});
  });

  it("strips extensions for the default docs-root-relative doc id", () => {
    expect(docusaurusDefaultDocId("guide.md")).toBe("guide");
    expect(docusaurusDefaultDocId("guides/one.mdx")).toBe("guides/one");
  });

  it("resolves reachable documents by frontmatter id over a divergent default filename id, and by autogenerated directory membership", async () => {
    const sidebars = parseDocusaurusSidebars(
      await readFile(join(FIXTURE_ROOT, "sidebars.js"), "utf8"),
    );
    const reachable = await docusaurusReachableDocumentPaths(FIXTURE_ROOT, "docs", sidebars);
    const relativePaths = [...reachable].map((path) => path.slice(FIXTURE_ROOT.length + 1)).sort();
    expect(relativePaths).toEqual([
      "docs/guide.md",
      "docs/guides/broken.md",
      "docs/guides/one.md",
      "docs/guides/two.md",
      "docs/intro.md",
    ]);
    expect(relativePaths).not.toContain("docs/standalone.md");

    const wrongIdSidebars = parseDocusaurusSidebars(
      'module.exports = { tutorialSidebar: ["guide"] };',
    );
    const wrongReachable = await docusaurusReachableDocumentPaths(
      FIXTURE_ROOT,
      "docs",
      wrongIdSidebars,
    );
    const wrongRelative = [...wrongReachable].map((path) => path.slice(FIXTURE_ROOT.length + 1));
    expect(wrongRelative).not.toContain("docs/guide.md");
  });

  it("validates the full Docusaurus source root end to end, leaving an unrelated broken document outside the closure", async () => {
    const applicability = await buildDocusaurusApplicability({
      root: FIXTURE_ROOT,
      changedPaths: [
        { path: "docs/guide.md", status: "modified" },
        { path: "docs/guides/one.md", status: "modified" },
      ],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).resolves.toEqual([
      { id: "documentation-source-applicability", status: "passed" },
      { id: "documentation-paths-readable", status: "passed" },
      { id: "documentation-relative-links", status: "passed" },
      { id: "documentation-navigation-targets", status: "passed" },
    ]);
  });

  it("rejects a changed document that is not reachable from the sidebars", async () => {
    const applicability = await buildDocusaurusApplicability({
      root: FIXTURE_ROOT,
      changedPaths: [{ path: "docs/standalone.md", status: "added" }],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).rejects.toMatchObject({ check: "documentation-navigation-targets", status: "failed" });
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).rejects.toThrow(/is not reachable from sidebars/u);
  });

  it("rejects a Docusaurus root missing its governing sidebars file", async () => {
    const root = await roots.create("docsfab-docusaurus-missing-sidebars-");
    await mkdir(join(root, "docs"), { recursive: true });
    await writeFile(join(root, "docs/intro.md"), "# Intro\n");
    await writeFile(join(root, "docusaurus.config.js"), 'module.exports = { title: "X" };\n');
    const applicability = await buildDocusaurusApplicability({
      root,
      changedPaths: [{ path: "docs/intro.md", status: "modified" }],
      configurationFiles: ["docusaurus.config.js"],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(root, applicability.changedPaths, applicability),
    ).rejects.toMatchObject({ check: "documentation-navigation-targets", status: "limitation" });
  });

  it("rejects a malformed docusaurus.config.js relevant to this adapter", async () => {
    const root = await roots.create("docsfab-docusaurus-bad-config-");
    await mkdir(join(root, "docs"), { recursive: true });
    await writeFile(join(root, "docs/intro.md"), "# Intro\n");
    await writeFile(
      join(root, "docusaurus.config.js"),
      'module.exports = require("./generated-config");\n',
    );
    await writeFile(
      join(root, "sidebars.js"),
      'module.exports = { tutorialSidebar: ["intro"] };\n',
    );
    const applicability = await buildDocusaurusApplicability({
      root,
      changedPaths: [{ path: "docs/intro.md", status: "modified" }],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(root, applicability.changedPaths, applicability),
    ).rejects.toMatchObject({ check: "documentation-navigation-targets", status: "limitation" });
  });

  it("still reserves an unimplemented adapter such as sphinx", async () => {
    const applicability = createDocumentationSourceApplicability({
      repositoryIdentitySha256: sha256("repository"),
      baseRevision: "a".repeat(40),
      candidateInputTreeSha256: sha256("candidate"),
      changedPaths: [{ path: "docs/intro.md", status: "modified" }],
      roots: [
        {
          root: ".",
          adapterId: "sphinx",
          adapterVersion: DOCUMENTATION_SOURCE_ADAPTER_VERSION,
          configurationFiles: [],
          navigationMode: "explicit",
          requiredPathClosureSha256: sha256("closure"),
          limitations: [],
        },
      ],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).rejects.toMatchObject({ check: "documentation-source-applicability", status: "limitation" });
  });

  it("derives a real Docusaurus applicability root with empty limitations and validates it end to end (F1)", async () => {
    const applicability = await deriveDocumentationSourceApplicability({
      candidateRoot: FIXTURE_ROOT,
      repositoryIdentitySha256: sha256("repository"),
      baseRevision: "a".repeat(40),
      candidateInputTreeSha256: sha256("candidate"),
      changedPaths: [
        { path: "docs/guide.md", status: "modified" },
        { path: "docs/guides/one.md", status: "modified" },
      ],
    });
    expect(applicability.roots).toEqual([
      expect.objectContaining({
        root: ".",
        adapterId: "docusaurus",
        navigationMode: "explicit",
        limitations: [],
      }),
    ]);
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).resolves.toEqual([
      { id: "documentation-source-applicability", status: "passed" },
      { id: "documentation-paths-readable", status: "passed" },
      { id: "documentation-relative-links", status: "passed" },
      { id: "documentation-navigation-targets", status: "passed" },
    ]);
  });

  it("rejects, through the real derive path, a changed document unreachable from the sidebars (F1 negative)", async () => {
    const applicability = await deriveDocumentationSourceApplicability({
      candidateRoot: FIXTURE_ROOT,
      repositoryIdentitySha256: sha256("repository"),
      baseRevision: "a".repeat(40),
      candidateInputTreeSha256: sha256("candidate"),
      changedPaths: [{ path: "docs/standalone.md", status: "added" }],
    });
    expect(applicability.roots[0]).toMatchObject({ adapterId: "docusaurus", limitations: [] });
    await expect(
      validateSourceAwareStructuralDocumentation(
        FIXTURE_ROOT,
        applicability.changedPaths,
        applicability,
      ),
    ).rejects.toMatchObject({ check: "documentation-navigation-targets", status: "failed" });
  });

  it("does not swallow the governing export when a type-only import omits its semicolon (F4)", () => {
    const source = [
      'import type { SidebarsConfig } from "@docusaurus/plugin-content-docs"',
      "",
      'module.exports = { tutorialSidebar: ["intro"] };',
    ].join("\n");
    expect(parseDocusaurusSidebars(source)).toEqual({
      tutorialSidebar: [{ type: "doc", id: "intro" }],
    });
  });

  it("does not swallow the governing export when a default type-only import omits its semicolon (F4)", () => {
    const source = [
      'import type SidebarsConfig from "@docusaurus/plugin-content-docs"',
      "",
      'export default { tutorialSidebar: ["intro"] };',
    ].join("\n");
    expect(parseDocusaurusSidebars(source)).toEqual({
      tutorialSidebar: [{ type: "doc", id: "intro" }],
    });
  });

  it("fails closed at the applicability gate for a broken-linked root README.md, rather than silently passing (F5)", async () => {
    const root = await roots.create("docsfab-docusaurus-outside-docs-");
    await mkdir(join(root, "docs"), { recursive: true });
    await writeFile(join(root, "docs/intro.md"), "# Intro\n");
    await writeFile(join(root, "docusaurus.config.js"), 'module.exports = { title: "X" };\n');
    await writeFile(
      join(root, "sidebars.js"),
      'module.exports = { tutorialSidebar: ["intro"] };\n',
    );
    await writeFile(join(root, "README.md"), "[Missing](does-not-exist.md)\n");
    const applicability = await deriveDocumentationSourceApplicability({
      candidateRoot: root,
      repositoryIdentitySha256: sha256("repository"),
      baseRevision: "a".repeat(40),
      candidateInputTreeSha256: sha256("candidate"),
      changedPaths: [{ path: "README.md", status: "added" }],
    });
    expect(applicability.roots[0]).toMatchObject({
      adapterId: "docusaurus",
      limitations: ["mixed-root-ownership"],
    });
    await expect(
      validateSourceAwareStructuralDocumentation(root, applicability.changedPaths, applicability),
    ).rejects.toMatchObject({ check: "documentation-source-applicability", status: "limitation" });
  });
});
